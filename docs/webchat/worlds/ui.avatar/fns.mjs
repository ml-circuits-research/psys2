// ui.avatar on the matrix reasoner (spec 15). The operations (ops.mjs: the DiceBear characters, the resolution of words to parts and colors, the moods, the offers to
// become another character) are unchanged and keep working on the session state; how the avatar looks is also wires of the library (matrix.sop): one ui.avatar.look
// (the character that is shown, its name and seed, the rest of the state as JSON), one ui.avatar.part for each part and one ui.avatar.color for each color of a
// character that was shown or changed. The library is the record: `toState` derives the state ops.mjs keeps (and the host draws) from the wires, `adopt` says which
// wires to tell and set for a state the operations changed, `guard` asks the rules whether the color or the part a request names exists, `undoWords` says what an
// undo took back in the world's words. The knowledge base (kb.sop) is generated by scripts/gen-ui-kb.mjs. Browser-safe; it imports its sibling ops.mjs.
import { initialState, CHARACTERS, CORE, SPOKEN_CHARACTER, COLOR_SAY, PART_KEYS } from './ops.mjs?v=5317a136be';

const dec = (t) => (typeof t === 'string' && t.startsWith('"') ? JSON.parse(t) : t);
const str = (v) => JSON.stringify(String(v));
const first = (w, k) => w?.attrs?.[k]?.[0];
const budget = { tick: (site, n = 1) => globalThis[Symbol.for('psys2.budget')]?.tick(site, n) };   // the turn's step budget (a no-op outside a turn)
const tokens = (o) => JSON.stringify(o);
const OWN = new Set(['character', 'name', 'seed', ...CHARACTERS]);   // kept in wires of their own; everything else (the chips, the caption, an offer, the last looks) is one JSON on the look wire
/** The undo list of the state keeps the whole look before each change; the library keeps them, so the wire keeps only the last (and the characters of the rest, for "why did you turn into ...?"). */
const compact = (u) => (Array.isArray(u) ? u.map((e, i) => (i === u.length - 1 ? e : { character: e?.character })) : u);
const restOf = (s) => {
  const r = Object.fromEntries(Object.entries(s).filter(([k, v]) => !OWN.has(k) && v !== undefined));
  if (r.undo) r.undo = compact(r.undo);
  return r;
};
const idPart = (x) => String(x).replace(/[^\w-]/g, '_');   // the id of a kb wire (scripts/gen-ui-kb.mjs)
const tok = (v) => (/^[\w.-]+$/.test(String(v)) ? String(v) : str(v));   // a variant id or a hex color as the wires write it (an atom, or a string when it is not one)
const same = (a, b) => {
  const ka = Object.keys(a ?? {}).filter((k) => !k.startsWith('core.')), kb = Object.keys(b ?? {});
  if (ka.length !== kb.length) return false;
  for (const k of ka) { const x = a[k], y = b[k]; if (!y || x.length !== y.length) return false; for (let i = 0; i < x.length; i++) if (x[i] !== y[i]) return false; }
  return true;
};
const keysOf = (a) => Object.keys(a).filter((k) => !k.startsWith('core.')).sort().join();
const line = (id, w) => `@${id} ${w.type} ${Object.entries(w.attrs).map(([k, vs]) => vs.map((v) => `${k}=${v}`).join(' ')).join(' ')}`;

/** The state ops.mjs keeps (the host draws it), derived from the wires. A character nobody showed or changed is not in it: the operations fill it in when they need it. */
export function toState({ find }) {
  const look = find('ui.avatar.look')[0];
  const parts = find('ui.avatar.part'), colors = find('ui.avatar.color');
  const s = initialState();
  if (look) {
    Object.assign(s, JSON.parse(dec(first(look, 'rest'))));
    s.character = dec(first(look, 'character'));
    s.name = dec(first(look, 'name'));
    s.seed = dec(first(look, 'seed'));
  }
  const byCh = new Map();
  for (const w of parts) { budget.tick('ui.avatar.toState'); const ch = first(w, 'ch'); (byCh.get(ch) ?? byCh.set(ch, { parts: [], colors: [] }).get(ch)).parts.push(w); }
  for (const w of colors) { budget.tick('ui.avatar.toState'); const ch = first(w, 'ch'); (byCh.get(ch) ?? byCh.set(ch, { parts: [], colors: [] }).get(ch)).colors.push(w); }
  const n = (w) => Number(first(w, 'n') ?? 0);
  for (const [ch, { parts: ps, colors: cs }] of byCh) {
    const o = {};
    for (const w of ps.sort((a, b) => n(a) - n(b))) o[first(w, 'key')] = dec(first(w, 'value'));
    o.colors = {};
    for (const w of cs.sort((a, b) => n(a) - n(b))) o.colors[first(w, 'key')] = dec(first(w, 'hex'));
    s[ch] = o;
  }
  for (const w of find('ui.avatar.start')) { budget.tick('ui.avatar.toState'); const ch = first(w, 'ch'); if (!s[ch]) s[ch] = JSON.parse(dec(first(w, 'look'))); }   // an AV character nobody changed has its start look (the kb)
  return s;
}

const isInitial = (s) => {
  const i = initialState();
  if (s.character !== i.character || s.name !== i.name || s.seed !== i.seed) return false;
  for (const ch of CHARACTERS) if (i[ch] ? tokens(s[ch]) !== tokens(i[ch]) : false) return false;   // the characters the operations filled in from the data (ensure) are not a change
  return tokens(restOf(s)) === tokens(restOf(i));
};

/** The wires a state asks for: { id: { type, attrs: { key: [token] } } }. Only a character that is shown, was changed or is already wired is asked for. */
function wiresOf(state, wired) {
  const out = {};
  if (isInitial(state)) return out;
  out['av.look'] = { type: 'ui.avatar.look', attrs: { character: [tok(state.character)], name: [str(state.name)], seed: [str(state.seed)], rest: [str(tokens(restOf(state)))], char: [`$kb.av.char.${state.character}`] } };
  const init = initialState();
  for (const ch of CHARACTERS) {
    const o = state[ch];
    if (!o) continue;
    if (!(ch === state.character || wired.has(ch) || (init[ch] && tokens(o) !== tokens(init[ch])))) continue;
    let n = 0;
    for (const [key, value] of Object.entries(o)) {
      if (key === 'colors') continue;
      budget.tick('ui.avatar.wires');
      out[`av.p.${ch}.${key}`] = { type: 'ui.avatar.part', attrs: { ch: [ch], key: [key], value: [tok(value)], n: [String(n++)], slot: [`$kb.av.slot.${ch}.${idPart(key)}`] } };
    }
    n = 0;
    for (const [key, hex] of Object.entries(o.colors ?? {})) {
      budget.tick('ui.avatar.wires');
      out[`av.c.${ch}.${key}`] = { type: 'ui.avatar.color', attrs: { ch: [ch], key: [key], hex: [tok(hex)], n: [String(n++)] } };
    }
  }
  return out;
}

/**
 * The library wires for a state the operations changed: { retract: [ids], tell: 'text', sets: [{ id, key, value }] } (a wire that already says it is left alone).
 * A wire whose single values changed (a part, a color, the look) gets the new values set in place; a wire that is no longer wanted is retracted.
 */
export function adopt({ state, find }) {
  const have = new Map();
  const wired = new Set();
  for (const t of ['ui.avatar.look', 'ui.avatar.part', 'ui.avatar.color']) for (const w of find(t)) {
    budget.tick('ui.avatar.adopt');
    have.set(w.id, w);
    if (t !== 'ui.avatar.look') wired.add(first(w, 'ch'));
  }
  const want = wiresOf(state, wired);
  const retract = [], tell = [], sets = [], replace = [];
  for (const [id, h] of have) {
    const w = want[id];
    if (!w) { retract.push(id); continue; }
    if (same(h.attrs, w.attrs)) continue;
    const single = keysOf(h.attrs) === keysOf(w.attrs) && Object.keys(w.attrs).every((k) => w.attrs[k].length === 1 && (h.attrs[k] ?? []).length === 1);
    if (!single) { replace.push({ id, type: w.type, attrs: w.attrs }); continue; }   // the wire keeps its id (library R6.9)
    for (const [k, vs] of Object.entries(w.attrs)) if (h.attrs[k][0] !== vs[0]) sets.push({ id, key: k, value: vs[0] });
  }
  for (const [id, w] of Object.entries(want)) if (!have.has(id)) tell.push(line(id, w));
  return { retract, tell: tell.join('\n'), sets, replace };
}

/** An undo brought back an offer that a confirmation had answered ("say yes to become the emoji"): the offer is closed again, as the operations forget it when it is answered (spec 15). */
export function closeOffer(state) { state.pending = null; state.inputMode = null; }

// ---- guard: does the color, the part that is to be colored exist? (asked to the rules) -------------------------------------------------------------------------
const UNKNOWN_NOTE = /\b(i do not (know|have|speak)|unknown)\b/i;
const atom = (x) => String(x).toLowerCase().replace(/[^\w.-]/g, '_');
const COLORED = new Set(['avatar.setColor', 'avatar.shiftColor', 'avatar.setPartColored']);
const reason = (r) => {
  const x = (r.violations ?? []).find((q) => q.why);
  if (!x) return null;
  const note = String(x.why).replace(/^"(.*)"$/, '$1').replace(/\\"/g, '"');
  return { status: 'unsupported', reason: UNKNOWN_NOTE.test(note) ? 'unknown_argument' : 'precondition_failed', note, why: note };
};
const plural = (label) => (/s$/.test(label) ? label : `${label}s`);

/** Refuses a request for a color nobody knows, or for the color of a part that has none, with the reason the rules give: { status: 'unsupported', reason, note }, or null. */
export function guard({ action, args, state, check, find }) {
  if (!COLORED.has(action)) return null;
  const spaced = (x) => String(x ?? '').replace(/_/g, ' ');
  if (action !== 'avatar.shiftColor' && args?.color !== undefined) {
    const r = check({ wires: `@av.q ui.avatar.want kind=colorname name=${atom(args.color)} word=${str(spaced(args.color))}` });
    if (!r.ok) return reason(r);
  }
  if (action !== 'avatar.setPartColored' && args?.part !== undefined && !state?.face?.active && !['hat', 'earring'].includes(args.part)) {   // a drawn face answers for its own parts (faceops.mjs)
    const part = atom(args.part), ch = state?.character ?? 'robot';
    const key = (PART_KEYS[args.part] ?? []).find((k) => find('ui.avatar.slot').some((w) => first(w, 'ch') === ch && first(w, 'key') === k));
    const r = check({ wires: `@av.q ui.avatar.want kind=${key ? 'paintlist' : 'paint'} ch=${ch} part=${part} word=${str(spaced(args.part))}${key ? ` key=${key}` : ''}` });
    if (!r.ok) return reason(r);
  }
  return null;
}

// ---- undo, words ------------------------------------------------------------------------------------------------------------------------------------------
const joinAnd = (a) => (a.length <= 1 ? a.join('') : `${a.slice(0, -1).join(', ')} and ${a.at(-1)}`);
const COLOR_WORD = (key) => (COLOR_SAY[key] ?? [key, 'is']);

/** What "undo" says once the library went back, from the states before and after: the character it is again, the parts and colors that are as they were. */
export function undoWords({ before, after }) {
  if (!before) return { status: 'missing', note: 'There is nothing to undo.' };
  const parts = [];
  if (before.character !== after.character) parts.push(`I am ${SPOKEN_CHARACTER[after.character] ?? after.character} again`);
  const was = new Set((before.caption?.text ?? '').split(' · ')), now = (after.caption?.text ?? '').split(' · ').filter((x) => x && !was.has(x));   // the caption says each part in words: the ones that changed
  if (before.character === after.character) for (const item of now) parts.push(`I have ${item.replace(/\bits\b/g, 'my')} again`);
  for (const ch of CHARACTERS) {
    const b = before[ch], a = after[ch];
    if (!a) continue;
    for (const [key, hex] of Object.entries(a.colors ?? {})) {
      if (b?.colors?.[key] === hex) continue;
      const [label, verb] = COLOR_WORD(key);
      parts.push(`my ${label} ${verb} as it was`);
    }
  }
  if (before.name !== after.name) parts.push(`my name is ${after.name} again`);
  if (before.seed !== after.seed) parts.push(`my seed is ${after.seed} again`);
  const shown = parts.length > 4 ? [...parts.slice(0, 3), `${parts.length - 3} more things`] : parts;
  return { value: `OK, I went back to how I was before${shown.length ? `: ${joinAnd(shown)}` : ''}.` };
}

/**
 * Whether the state changed: the host compares this instead of stringifying the whole state. The list of looks to undo is long (its length and its last entry stand for it)
 * and an AV character that is not shown is its start look (the operations fill it in, the kb says it): it is not part of the key, so a state nobody changed has the key of the
 * empty instance and costs no instance.
 */
export function stateKey(s) {
  const { undo, ...rest } = s;
  for (const ch of CHARACTERS) if (!CORE.includes(ch) && ch !== s.character) delete rest[ch];
  return JSON.stringify([rest, undo?.length ?? 0, undo?.at(-1)?.character]);
}
