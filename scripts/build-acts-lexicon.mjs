// Writes worlds/acts/lexicon.sop and worlds/acts/verbs.generated.mjs from the verbs of the knowledge world `k.actions` (spec 21): one `k.actions.verb` wire per verb and act
// ("get rid of", "take off", "put on" ...). The catalog is read as the catalog is read everywhere: its shards. Default source: the fixture copy in tests/fixtures/catalog
// (made by scripts/make-catalog-fixture.mjs); give a catalog folder (docs/worlds of sop-knowledge-worlds) to build from the real one. The files are generated, never edited;
// tests/acts.test.mjs checks them. There is no local seed of verbs any more: a verb that is missing is a miss of class "act phrase" for the knowledge repo.
import { writeFile, readFile, readdir } from 'node:fs/promises';
import path from 'node:path';
import { REL_WORDS, DET_WORDS, DIR_WORDS } from '../worlds/acts/acts.mjs';

/** The act names of this module for the act names of k.actions. */
const LOCAL = { change: 'set', take_apart: 'apart' };
const phrase = (id, doc, words, frame = false) => `@phrase.acts.${id} core.phrase\n${frame ? '' : '    frame=false\n'}    doc=${JSON.stringify(doc)}\n${words.map((w) => `    alt=${w}`).join('\n')}\n`;

/** { act: [verb with underscores] } from the verb wires of k.actions (in catalog order, no duplicates). */
export async function verbsOf(catalogDir = path.join(import.meta.dirname, '../tests/fixtures/catalog')) {
  const dir = path.join(catalogDir, 'k.actions/shards');
  const out = {};
  for (const f of (await readdir(dir)).filter((x) => /^verbs-.*\.sop$/.test(x)).sort()) {
    for (const line of (await readFile(path.join(dir, f), 'utf8')).split('\n')) {
      const m = /^@k\.actions\.verb\.\S+ k\.actions\.verb text=("[^"]*"|\S+) act=("[^"]*"|\S+)/.exec(line);
      if (!m) continue;
      const raw = m[2].replace(/"/g, '').replace(/ /g, '_'), act = LOCAL[raw] ?? raw, text = m[1].replace(/"/g, '').toLowerCase().replace(/[^a-z' -]/g, '').trim().replace(/\s+/g, '_');
      if (!text || text.length < 2) continue;
      const list = (out[act] ??= []);
      if (!list.includes(text)) list.push(text);
    }
  }
  return out;
}
export async function build(catalogDir) {
  const verbs = await verbsOf(catalogDir);
  const out = ['@gen.acts.note core.note\n    text="Generated by scripts/build-acts-lexicon.mjs from the verbs of the knowledge world k.actions (spec 21). Never edited by hand."\n'];
  for (const [act, words] of Object.entries(verbs)) out.push(phrase(`verb.${act}`, `Verbs of the act ${act} (k.actions).`, words));
  out.push(phrase('det', 'Determiners before a thing.', DET_WORDS, true));
  out.push(`@lex.acts.rel core.lexicon\n    class=trigger\n    doc="Relation words of the role place (at, on, next to ...)."\n${REL_WORDS.map((w) => `    word=${w}`).join('\n')}\n`);
  out.push(`@lex.acts.dir core.lexicon\n    class=trigger\n    doc="Direction words of a move of a thing (closer together, apart, higher, lower ...)."\n${DIR_WORDS.map((w) => `    word=${w}`).join('\n')}\n`);
  return { lexicon: out.join('\n'), module: `// GENERATED by scripts/build-acts-lexicon.mjs from the verbs of k.actions. Never edited by hand.\nexport const ACT_VERBS = ${JSON.stringify(verbs)};\n` };
}
if (import.meta.url === `file://${process.argv[1]}`) {
  const { lexicon, module } = await build(process.argv[2]);
  await writeFile(new URL('../worlds/acts/lexicon.sop', import.meta.url), lexicon);
  await writeFile(new URL('../worlds/acts/verbs.generated.mjs', import.meta.url), module);
  console.log('worlds/acts/lexicon.sop and verbs.generated.mjs written');
}
