// Writes worlds-pilot/ui.avatar/schema.sop from the slots of the catalog k.faces (here: the bundled default face generated from it). One kind per slot, the slot's other
// names as words; the attributes are the ones the face logic understands (colour, size, place). When k.faces changes: node scripts/build-default-face.mjs, then this, then
// node scripts/build-schema-world.mjs worlds-pilot/ui.avatar. (spec 21, pilot P1)
import { writeFile } from 'node:fs/promises';
import { DEFAULT_FACE } from '../worlds/ui.avatar/default-face.mjs';

const plain = (n) => n.replace(/_/g, ' ');
export function build(data = DEFAULT_FACE) {
  const out = [`@face acts.schema
    noun="face"
    doc="The avatar's face: one kind per slot of the knowledge world k.faces, generated by scripts/build-avatar-schema.mjs. The effects (variants, presets, expressions, size and place) are the face logic over the catalog (hooks.mjs)."
    hooks=hooks.mjs
    acts=make
    acts=remove
    acts=change
    acts=place
    acts=ask
    acts=undo
    acts=redo
    acts=save
    acts=load
    own=animate:avatar.animate
    own=setName:avatar.setName
    own=askName:avatar.askName
    own=nameOf:avatar.nameOf
    own=setPartUnknown:avatar.setPartUnknown
    sample=hat
    self=yes
    be=yes
    has=yes
    dir=yes
    bare=yes
    name=yes
    limit.items=40
    limit.history=40`];
  const ks = [];
  for (const s of data.slots) {
    const words = new Set([plain(s.name), s.name.split('_')[0], ...(data.aliases[s.name] ?? []).map((a) => a.toLowerCase())]);
    words.delete(plain(s.name));
    out.push(`@face.${s.name} acts.kind\n    plural=${s.name}${/s$/.test(s.name) ? "" : "s"}${[...words].map((w) => `\n    word=${w.replace(/\s+/g, '_')}`).join('')}`);
    ks.push(s.name);
  }
  out.push(`@face.moment acts.kind\n    plural=moments${['wink', 'nod', 'dance', 'wave', 'spin', 'jump', 'bounce', 'wiggle', 'blink'].map((w) => `\n    word=${w}`).join('')}`);
  const of = [...ks].map((k) => `\n    of=${k}`).join('');
  out.push(`@face.colour acts.attr${of}\n    type=colour\n    word=color`);
  out.push(`@face.size acts.attr${of}\n    type=number\n    min=0.6\n    max=1.5\n    default=1\n    more=bigger\n    more=larger\n    more=longer\n    more=wider\n    less=smaller\n    less=tinier\n    less=shorter\n    less=narrower`);
  return `${out.join('\n\n')}\n`;
}
if (import.meta.url === `file://${process.argv[1]}`) { await writeFile(new URL('../worlds-pilot/ui.avatar/schema.sop', import.meta.url), build()); console.log('worlds-pilot/ui.avatar/schema.sop written'); }
