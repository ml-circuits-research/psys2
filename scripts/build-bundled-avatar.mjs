// The Avatar area's offline catalog subset, GENERATED from the pinned catalog: the schemas of the area's modules
// (worlds/ui.avatar/area.sop: instance and knowledge) with their dependency closure, and the knowledge shards of
// the style its first face declares, with an index listing only what is bundled. The page reads the catalog when
// it can; this subset lets the area start with no network and lets Node tests run without a catalog checkout.
//   node scripts/build-bundled-avatar.mjs [--check]
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { World, str } from '../src/vendor/sopworld/sopworld.mjs';
import { catalogFolder, emit, done, stamp } from './lib/generated.mjs';

const { dir, commit } = await catalogFolder();
const ROOT = path.join(import.meta.dirname, '..');
const declaration = new World();
if (!declaration.load(readFileSync(path.join(ROOT, 'worlds/ui.avatar/area.sop'), 'utf8')).ok) throw Error('invalid area.sop');
const read = (fact, key) => (fact.attrs[key] ?? []).map((raw) => raw.startsWith('"') ? str(raw) : raw);
const [area] = declaration.ofType('app.area'), [first] = declaration.ofType('app.area.make');
const knowledge = read(area, 'knowledge'), modules = [...read(area, 'instance'), ...knowledge], style = read(first, 'style')[0];
const index = JSON.parse(readFileSync(path.join(dir, 'index.json'), 'utf8'));
const entries = new Map([...(index.worlds ?? []), ...(index.schemas ?? [])].map((entry) => [entry.id, entry]));
const files = {}, kept = { worlds: [], schemas: [] }, pending = [...modules], seen = new Set();
while (pending.length) {
  const id = pending.pop();
  if (seen.has(id)) continue;
  seen.add(id);
  const entry = entries.get(id);
  if (!entry) continue;
  files[entry.schema] = readFileSync(path.join(dir, entry.schema), 'utf8');
  // A knowledge module keeps the shards of the declared style and those that name no style in their file name.
  const styles = new Set((entry.shards ?? []).map((s) => path.basename(typeof s === 'string' ? s : s.path)).map((name) => name.split('-')[0]));
  const shards = knowledge.includes(id) ? (entry.shards ?? []).map((s) => typeof s === 'string' ? s : s.path)
    .filter((p) => { const name = path.basename(p, '.sop'); return name.startsWith(style + '-') || !name.includes('-') && name !== 'words'; }) : [];
  for (const shard of shards) files[shard] = readFileSync(path.join(dir, shard), 'utf8');
  (index.worlds?.some((w) => w.id === id) ? kept.worlds : kept.schemas).push({ id, schema: entry.schema, depends: entry.depends ?? [], shards });
  for (const dependency of entry.depends ?? []) pending.push(dependency);
  void styles;
}
files['index.json'] = JSON.stringify(kept);
emit(path.join(ROOT, 'src/knowledge/bundled-avatar.mjs'),
  `// GENERATED by scripts/build-bundled-avatar.mjs${stamp(commit)}. Do not edit.\n// The Avatar area's offline catalog subset: style ${style}, ${Object.keys(files).length} files.\nexport const BUNDLED_AVATAR_FILES = ${JSON.stringify(files)};\nexport const readBundledAvatar = async (file) => { if (!Object.hasOwn(BUNDLED_AVATAR_FILES, file)) throw Error('not-bundled:' + file); return BUNDLED_AVATAR_FILES[file]; };\n`);
done('build-bundled-avatar');
