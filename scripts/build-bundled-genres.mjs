// The document genres of the knowledge catalog (k.genres: genres, parts, steps, moves, registers) bundled for std.compose (spec 26). GENERATED, never copied by hand:
//   node scripts/build-bundled-genres.mjs <catalog folder (docs/worlds of sop-knowledge-worlds)>
// Writes src/knowledge/bundled-genres.mjs (the shard texts in the catalog's own format, without the sources shard).
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const dir = process.argv[2];
if (!dir) { console.error('usage: node scripts/build-bundled-genres.mjs <catalog folder>'); process.exit(1); }
const idx = JSON.parse(readFileSync(path.join(dir, 'index.json'), 'utf8')).worlds.find((w) => w.id === 'k.genres');
if (!idx) { console.error('the catalog has no k.genres'); process.exit(1); }
const files = Object.fromEntries(idx.shards.filter((s) => !/sources/.test(s.id)).map((s) => [s.path, readFileSync(path.join(dir, s.path), 'utf8')]));
writeFileSync(path.join(import.meta.dirname, '../src/knowledge/bundled-genres.mjs'),
  `// SPDX-License-Identifier: AGPL-3.0-only\n// GENERATED by scripts/build-bundled-genres.mjs from the knowledge catalog (k.genres version ${idx.version}: ${Object.keys(files).length} shards): do not edit by hand.\nexport const BUNDLED_GENRES = ${JSON.stringify({ version: idx.version, files })};\n`);
console.log(`bundled-genres.mjs: k.genres version ${idx.version}, ${Object.keys(files).length} shards`);
