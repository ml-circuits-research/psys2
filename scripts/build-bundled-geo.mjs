// The bundled k.geo subset: every country (with its borders, region, currency, languages), the groups, the continents, the other spellings of places and the cities of 500,000 people or more plus the
// capitals, as wires in the catalog's own format, GENERATED from the catalog (never written by hand), so that the map knows its countries and major cities with no network and before the catalog
// answers; the catalog adds the rest (every river, every smaller city) when reachable. Read SYNCHRONOUSLY by worlds/geo.map/places.mjs and src/knowledge/open-words.mjs (like the animals).
//   node scripts/build-bundled-geo.mjs <catalog folder>      (also run by scripts/build-bundled-subset.mjs)
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { createFacts } from '../src/knowledge/facts.mjs';
import { createKnowledgeSource } from '../src/loaders/knowledge-source.mjs';

const dir = process.argv[2];
if (!dir) { console.error('usage: node scripts/build-bundled-geo.mjs <catalog folder>'); process.exit(1); }
const ROOT = path.join(import.meta.dirname, '..');
const facts = createFacts({ source: createKnowledgeSource(dir) });
const q = (v) => (/^[^\s"=]+$/.test(v) ? v : JSON.stringify(v));
const line = (w) => `@${w.id} ${w.type} ${Object.entries(w.f).filter(([k]) => k !== 'core.source').flatMap(([k, vs]) => vs.map((v) => `${k}=${q(v)}`)).join(' ')}`;
const out = [], keys = new Set();
const add = (w) => { out.push(line(w)); for (const n of w.f.name ?? []) keys.add(String(n).toLowerCase()); };
for (const t of ['k.geo.country', 'k.geo.continent', 'k.geo.group']) for (const w of await facts.wires(t)) add(w);
for (const w of await facts.wires('core.word', { world: 'k.geo' })) { out.push(line(w)); for (const x of w.f.text ?? []) keys.add(String(x).toLowerCase()); }
const cities = (await facts.wires('k.geo.city')).filter((w) => Number(w.f.population?.[0] ?? 0) >= 500000 || w.f.capital_of?.length);
for (const w of cities) add(w);
const text = out.join('\n') + '\n';
writeFileSync(path.join(ROOT, 'src/knowledge/bundled-geo.mjs'), `// SPDX-License-Identifier: AGPL-3.0-only\n// GENERATED by scripts/build-bundled-geo.mjs from the knowledge catalog (k.geo: countries, groups, continents, other spellings, cities of 500,000+ and capitals; licences as in the catalog's LICENSES.md): do not edit.\nexport const BUNDLED_GEO = ${JSON.stringify({ text, keys: [...keys].sort() })};\n`);
console.log(`bundled-geo.mjs: ${out.length} wires (${cities.length} cities), ${keys.size} names, ${text.length} bytes`);
