// The interest model of the knowledge catalog (k.interest: appraisals, measures, features) bundled for std.compose, which ranks facts by it (spec 26). GENERATED, never copied by hand:
//   node scripts/build-bundled-interest.mjs [<catalog folder (docs/worlds of sop-knowledge-worlds)>] [--check]     (no folder: the catalog at the pin; --check: exit 1 when stale)
// Writes src/knowledge/bundled-interest.mjs (the shard text in the catalog's own format).
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { catalogFolder, emit, done, stamp } from './lib/generated.mjs';

const { dir, commit } = await catalogFolder();
const idx = JSON.parse(readFileSync(path.join(dir, 'index.json'), 'utf8')).worlds.find((w) => w.id === 'k.interest');
if (!idx) { console.error('the catalog has no k.interest'); process.exit(1); }
const files = Object.fromEntries(idx.shards.filter((s) => /features/.test(s.id)).map((s) => [s.path, readFileSync(path.join(dir, s.path), 'utf8')]));
emit(path.join(import.meta.dirname, '../src/knowledge/bundled-interest.mjs'),
  `// SPDX-License-Identifier: AGPL-3.0-only\n// GENERATED by scripts/build-bundled-interest.mjs from the knowledge catalog (k.interest version ${idx.version}: appraisals, measures and features${stamp(commit)}): do not edit by hand.\nexport const BUNDLED_INTEREST = ${JSON.stringify({ version: idx.version, files })};\n`);
console.log(`bundled-interest.mjs: k.interest version ${idx.version}, ${Object.keys(files).length} shard(s)`);
done('build-bundled-interest');
