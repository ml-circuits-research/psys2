#!/usr/bin/env node
// SPDX-License-Identifier: AGPL-3.0-only
// Writes src/knowledge/bundled-names.mjs: the names of the animals of the bundled k.animals subset (src/knowledge/bundled-animals.mjs), a few KB, so that the speller knows them as real
// words with no catalog attached (offline, tests) without loading the 160 KB bundle (spec 23 section 11). Run after scripts/build-bundled-subset.mjs.
//   node scripts/build-bundled-names.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { animalNames } from '../src/knowledge/animals.mjs';

const OUT = new URL('../src/knowledge/bundled-names.mjs', import.meta.url);
const names = [...new Set(animalNames().map((n) => String(n).toLowerCase()))].sort();
const text = `// SPDX-License-Identifier: AGPL-3.0-only
// GENERATED by scripts/build-bundled-names.mjs from src/knowledge/bundled-animals.mjs (k.animals, CC0-1.0): the names of the bundled animals, real words for the speller. Never edited by hand.
export const BUNDLED_NAMES = ${JSON.stringify(names)};
`;
if (process.argv.includes('--check')) { const cur = readFileSync(OUT, 'utf8'); if (cur !== text) { console.error('src/knowledge/bundled-names.mjs is stale'); process.exit(1); } console.log('fresh'); }
else { writeFileSync(OUT, text); console.log(`wrote ${names.length} names`); }
