// The published words and expectations a request needs (spec 28; sopworld 0.149 readRequest / reviseRequest / planRequest / sayRequest), bundled from the knowledge catalog. GENERATED:
//   node scripts/build-bundled-request.mjs [<catalog folder (docs/worlds of sop-knowledge-worlds)>] [--check]     (no folder: the catalog at the pin; --check: exit 1 when stale)
// Writes src/knowledge/bundled-request.mjs: one SOP text with the w.lang.en cues, closed words, number words, inflection and replies; the k.actions verbs; the k.expect amounts,
// scale, makes and parts; the w.dialogue revisions; the k.colours names (the types of the library's own example, examples/request-app.mjs requestLanguage). Sources dropped.
import { readFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import path from 'node:path';
import { catalogFolder, emit, done, stamp } from './lib/generated.mjs';

const TYPES = {
  'w.lang.en': ['cue', 'det', 'prep', 'pron', 'skip', 'number', 'inflect', 'irregular', 'reply', 'count', 'onset', 'anaphor', 'wh', 'closed', 'rule', 'construction', 'word'].map((t) => `w.lang.en.${t}`),   // rule / construction / word: the NP grammar ("everything": set=all; sopworld 0.153 requestLanguage)
  'k.actions': ['k.actions.verb'],
  'k.expect': ['k.expect.amount', 'k.expect.scale', 'k.expect.make', 'k.expect.part'],
  'w.dialogue': ['w.dialogue.revision'],
  'k.colours': ['k.colours.basic', 'k.colours.colour'],
};
const { dir, commit } = await catalogFolder();
const QUOTED = '"(?:[^"\\\\]|\\\\.)*"';
const DROP = new RegExp(`\\s(?:core\\.source|doc|note)=(?:${QUOTED}|\\S+)`, 'g');
const lines = [];
const counts = {};
for (const [world, types] of Object.entries(TYPES)) {
  const want = new Set(types);
  const files = [];
  const walk = (d) => { for (const f of readdirSync(d).sort()) { const p = path.join(d, f); if (statSync(p).isDirectory()) walk(p); else if (p.endsWith('.sop')) files.push(p); } };
  if (!existsSync(path.join(dir, world))) { console.error(`the catalog has no ${world}`); process.exit(1); }
  walk(path.join(dir, world));
  for (const f of files) for (const l of readFileSync(f, 'utf8').split('\n')) {
    const t = l.startsWith('@') ? l.split(/\s+/)[1] : null;
    if (!t || !want.has(t) || (/=\?[a-z]/.test(l) && !/^w\.lang\.en\.(?:rule|construction)$/.test(t))) continue;   // a pattern of a rule (a variable) is not a fact to bundle, except the grammar's own rules
    lines.push(l.replace(DROP, ''));
    counts[t] = (counts[t] ?? 0) + 1;
  }
}
emit(path.join(import.meta.dirname, '../src/knowledge/bundled-request.mjs'),
  `// SPDX-License-Identifier: AGPL-3.0-only\n// GENERATED by scripts/build-bundled-request.mjs from the knowledge catalog (${Object.entries(counts).map(([t, n]) => `${t} ${n}`).join(', ')}${stamp(commit)}). Never edited by hand.\nexport const BUNDLED_REQUEST = ${JSON.stringify(lines.join('\n'))};\n`);
console.log(`bundled-request.mjs: ${lines.length} facts`);
done('build-bundled-request');
