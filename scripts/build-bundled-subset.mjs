// KNOWLEDGE-OUT step 3: the small bundled subset of the catalog that a first visit has with no network (the "first paint"), GENERATED from the catalog, never copied by hand:
//   - every colour name of k.values (name, RGB, basic colour) and every number word (cardinal, ordinal, group, fraction),
//   - the drawings (k.objects) of the built-in kinds of the drawing board (the old hand drawings), by the generic reading `facts.wires`,
//   - and, through the two scripts that already generate from the catalog, the act verbs of k.actions (worlds/acts/verbs.generated.mjs) and the default face of k.faces
//     (worlds/ui.avatar/default-face.mjs), run here so that one command refreshes everything bundled.
//   node scripts/build-bundled-subset.mjs <catalog folder (docs/worlds of sop-knowledge-worlds)> [--no-acts] [--no-face]
// Writes src/knowledge/bundled-values.mjs and bundled-objects.mjs: shard texts in the catalog's own format (path -> text) plus the index entries. The catalog replaces it when reachable
// (src/knowledge/bundled-source.mjs layers the two), and the colour and number readers (src/knowledge/values.mjs) are seeded from it.
import { writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { createFacts } from '../src/knowledge/facts.mjs';
import { createKnowledgeSource } from '../src/loaders/knowledge-source.mjs';
import { readFileSync } from 'node:fs';

const dir = process.argv[2];
if (!dir) { console.error('usage: node scripts/build-bundled-subset.mjs <catalog folder>'); process.exit(1); }
const ROOT = path.join(import.meta.dirname, '..');
// the kinds the drawing board has built in: read from its source text (importing it would need the very files this script writes)
const KIND_ORDER = [...(/export const KIND_ORDER = \[([^\]]*)\]/.exec(readFileSync(path.join(ROOT, 'worlds/art.draw/scene.mjs'), 'utf8'))?.[1] ?? '').matchAll(/'([^']+)'/g)].map((m) => m[1]);
const facts = createFacts({ source: createKnowledgeSource(dir) });

const q = (v) => (/^[^\s"=]+$/.test(v) ? v : JSON.stringify(v));
const line = (w) => `@${w.id} ${w.type} ${Object.entries(w.f).filter(([k]) => k !== 'core.source').flatMap(([k, vs]) => vs.map((v) => `${k}=${q(v)}`)).join(' ')}`;
const sources = new Set();
const shards = {}, index = [];
function put(id, header, wires, keys) {
  const text = `# ${header}\n# GENERATED by scripts/build-bundled-subset.mjs from the catalog; the catalog replaces it when reachable.\n\n${wires.map(line).join('\n')}\n`;
  shards[`${id}.sop`] = text;
  index.push({ world: id.split('/')[0], id, path: `${id}.sop`, keys: [...new Set(keys.map((k) => String(k).toLowerCase()))], sources: ['bundled'] });
}

const colours = await facts.wires('k.values.colour');
const numbers = await facts.wires('k.values.number');
if (!colours.length || !numbers.length) { console.error('the catalog has no k.values (colours, numbers): nothing to bundle'); process.exit(1); }
// two facts the colour lexicon needs and the catalog has in other worlds, kept on the bundled colour wires: `thing=true` when the name is also a drawable thing of k.objects (a tomato, a plum),
// `core=true` when k.colours lists it as one of its colours (the catalog's own judgement of a real colour)
const objectNames = new Set((await facts.wires('k.objects.object')).map((w) => String(w.f.name?.[0]).toLowerCase()));
const coreNames = new Set((await facts.wires('k.colours.colour')).map((w) => String(w.f.name?.[0]).toLowerCase()));
for (const w of colours) { const n = w.f.name[0].toLowerCase(); if (objectNames.has(n)) w.f.thing = ['true']; if (coreNames.has(n)) w.f.core = ['true']; }
put('k.values/shards/bundled', `${colours.length} colour names with their RGB and ${numbers.length} number words of k.values (colours carry thing= and core=, derived from k.objects and k.colours)`, [...colours, ...numbers], [...colours.map((w) => w.f.name[0]), ...numbers.map((w) => w.f.text[0])]);

// the drawings of the built-in kinds of the drawing board: object, parts and points as the catalog has them
const objects = [];
const kept = [], pointsOf = new Map();
for (const kind of KIND_ORDER) {
  const o = await facts.wires('k.objects.object', { key: kind });
  const obj = o.find((w) => w.f.name?.[0] === kind);
  if (!obj) continue;
  const parts = (await facts.wires('k.objects.part', { key: kind })).filter((w) => w.f.of?.[0] === kind);
  if (!pointsOf.has(obj.shard)) pointsOf.set(obj.shard, await facts.wires('k.objects.point', { shard: (x) => x.id === obj.shard }));
  const ids = new Set(parts.map((p) => `$${p.id}`)), pts = pointsOf.get(obj.shard).filter((w) => ids.has(w.f.part?.[0]));
  objects.push(obj, ...parts, ...pts); kept.push(kind);
}
put('k.objects/shards/bundled', `the drawings of the kinds the drawing board has built in (${kept.length}: ${kept.join(', ')})`, objects, kept);

const banner = (what) => `// SPDX-License-Identifier: AGPL-3.0-only\n// GENERATED by scripts/build-bundled-subset.mjs from the knowledge catalog (${what}; licences as in the catalog's LICENSES.md): do not edit by hand.\n// The small subset a first visit has with no network; the catalog replaces it when reachable.\n`;
// two modules: the colour and number words (read by the formalizer and every world through src/knowledge/values.mjs) and the drawings (read only through the bundled source)
const pick = (re) => ({ shards: Object.fromEntries(Object.entries(shards).filter(([k]) => re.test(k))), index: index.filter((e) => re.test(e.path)) });
const v = pick(/^k\.values\//), o = pick(/^k\.objects\//);
const valuesOut = `${banner('k.values: colour names with RGB and number words')}export const BUNDLED_VALUES = ${JSON.stringify(v.shards)};\nexport const BUNDLED_VALUES_INDEX = ${JSON.stringify(v.index)};\n`;
const objectsOut = `${banner('k.objects: the drawings of the built-in kinds of the drawing board')}export const BUNDLED_OBJECTS = ${JSON.stringify(o.shards)};\nexport const BUNDLED_OBJECTS_INDEX = ${JSON.stringify(o.index)};\n`;
writeFileSync(path.join(ROOT, 'src/knowledge/bundled-values.mjs'), valuesOut);
writeFileSync(path.join(ROOT, 'src/knowledge/bundled-objects.mjs'), objectsOut);
const out = valuesOut + objectsOut;
console.log('no drawing in the catalog for:', KIND_ORDER.filter((k) => !kept.includes(k)).join(', '));
console.log(`bundled-values.mjs ${valuesOut.length} bytes, bundled-objects.mjs ${objectsOut.length} bytes: ${colours.length} colours, ${numbers.length} numbers, ${kept.length} drawings (${objects.length} wires), ${out.length} bytes`);

if (!process.argv.includes('--no-acts')) { const r = spawnSync('node', [path.join(ROOT, 'scripts/build-acts-lexicon.mjs'), dir], { stdio: 'inherit' }); if (r.status) process.exit(r.status); }
if (!process.argv.includes('--no-face')) { const r = spawnSync('node', [path.join(ROOT, 'scripts/build-default-face.mjs'), dir], { stdio: 'inherit' }); if (r.status) process.exit(r.status); }
