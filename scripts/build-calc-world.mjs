/**
 * The readings of calc.arith from the PUBLISHED catalog (kids plan, ADR-011; Q18 K4 arithmetic words): writes worlds/calc.arith/patterns.sop and lexicon.sop from the frames
 * of the shard arithmetic of w.lang.en that compute over numbers (acts.calc.infix "what is 3 plus 4", acts.calc.prefix "what is double 6", acts.calc.split "share 12 between 3")
 * and their lexicons, and src/knowledge/calc-words.generated.mjs: every w.lang.en.calc word with the core.calc function it names (calc=add|sub|mul|div ..., factor=, markers),
 * the words the operations of calc.arith run with the library's builtins, and the story words calc.story gives the library's storyState (state, aggregate, extreme,
 * comparison). No phrasing is written here: a frame's words are the catalog's, its pattern is rebuilt by src/lang/en.mjs (createLangEn).
 *
 *   node scripts/build-calc-world.mjs [<catalog docs/worlds dir>] [--check]      (no folder: the catalog at the pin, scripts/lib/catalog-pin.mjs)
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createLangEn } from '../src/lang/en.mjs';
import { parse } from '../src/soplang/index.mjs';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const NS = 'calc.arith';
const DIR = join(REPO, 'worlds', NS);
/** The frames of numbers (the story frames, acts.calc.has / total / most / more, are calc.story's: its own patterns read them, storyState answers them). */
const FRAMES = new Set(['calc.infix', 'calc.prefix', 'calc.split']);
const LEXICONS = ['calc.infix', 'calc.prefix', 'calc.split'];
/** The priority offset of the frames (0: the catalog's; a world that stands behind a kids world while it is on would lower it, ADR-011). */
export const BEHIND = 0;
const CANONICAL = new Set(['calc.infix']);

const q = (s) => JSON.stringify(String(s));
const lexId = (n) => `lex.${NS}.${n.replace(/^calc\./, '')}`;
const us = (s) => String(s).toLowerCase().replace(/[\s-]+/g, '_');

function expand(match) {
  let m = match.replace(/\bL\b/g, '[$lang.lead.polite]?').replace(/\bD\b/g, '[$acts.det]?').replace(/\{(\w+):words\((\d+)\)\?\}/g, '{$1:words($2)?}');
  for (const n of LEXICONS) m = m.split(`lex.${n}}`).join(`${lexId(n)}}`);
  return `[$lang.lead.filler]? ${m} [$lang.tail.filler|please]?`;
}

export function build(catalog) {
  const shard = readFileSync(join(catalog, 'w.lang.en/shards/arithmetic.sop'), 'utf8');
  const lang = createLangEn({ arithmetic: shard }, null);
  const wires = parse(shard).wires;
  const str = (w, k) => w.entries.filter((e) => e.key === k).map((e) => String(e.value.v));
  const commit = (() => { try { return JSON.parse(readFileSync(join(catalog, 'index.json'), 'utf8')).version ?? null; } catch { return null; } })();
  const lex = [`# GENERATED by scripts/build-calc-world.mjs from the catalog world w.lang.en (shard arithmetic, K4)${commit ? ` (catalog index ${commit})` : ''}. Never edited by hand.\n`];
  for (const n of LEXICONS) {
    const w = wires.find((x) => x.type === 'w.lang.en.lex' && str(x, 'name')[0] === n);
    if (!w) continue;
    lex.push(`@${lexId(n)} core.lexicon\n    class=noun\n    doc=${q(str(w, 'doc')[0] ?? n)}\n${[...new Set(str(w, 'item').map(us))].map((i) => `    word=${i}\n`).join('')}`);
  }
  const frames = lang.frames('acts').filter((f) => FRAMES.has(f.id));
  const pats = [`# GENERATED by scripts/build-calc-world.mjs from the catalog world w.lang.en (shard arithmetic, K4${commit ? `, catalog index ${commit}` : ''}). Never edited by hand.\n`];
  for (const f of frames) {
    const emit = `@{_} core.request action=calc.compute arg.form=\\"${f.id.replace(/^calc\./, '')}\\"${f.args.map((a) => ` arg.${a}=\\"{${a}}\\"`).join('')} arg.text=\\"{segment}\\"`;
    pats.push(`@pat.${NS}.${f.id.replace(/^calc\./, '')} core.pattern\n    match=${q(expand(f.match))}\n    emit="${emit}"\n    kind=question\n    priority=${f.priority + BEHIND}\n    signal=true\n    example=${q(f.example)}\n${CANONICAL.has(f.id) ? `    canonical=${q(f.example)}\n` : ''}`);
  }
  const words = wires.filter((w) => w.type === 'w.lang.en.calc').map((w) => ({ text: str(w, 'text')[0], kind: str(w, 'kind')[0], form: str(w, 'form')[0] ?? null, calc: str(w, 'calc')[0] ?? null, factor: str(w, 'factor')[0] !== undefined ? Number(str(w, 'factor')[0]) : null, markers: str(w, 'marker'), state: str(w, 'state')[0] ?? null }));
  const mjs = `// GENERATED by scripts/build-calc-world.mjs from the catalog world w.lang.en (shard arithmetic, K4${commit ? `; catalog index ${commit}` : ''}). Never edited by hand.\n// SPDX-License-Identifier: CC0-1.0 (the catalog's licence)\n/** The words of arithmetic: { text, kind (operator | comparison | aggregate | extreme | state), form, calc (the core.calc builtin), factor, markers, state }. */\nexport const CALC_WORDS = ${JSON.stringify(words)};\n`;
  return { 'patterns.sop': pats.join('\n'), 'lexicon.sop': lex.join('\n'), 'calc-words.generated.mjs': mjs, frames: frames.length };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  let catalog = process.argv.slice(2).find((a) => !a.startsWith('--'));
  if (!catalog) catalog = (await import('./lib/catalog-pin.mjs')).pinnedCatalog().dir;
  if (!existsSync(join(catalog, 'w.lang.en/shards/arithmetic.sop'))) { console.error('usage: node scripts/build-calc-world.mjs [<catalog docs/worlds dir with w.lang.en/shards/arithmetic.sop>] [--check]'); process.exit(2); }
  const out = build(catalog);
  let stale = 0;
  for (const name of ['patterns.sop', 'lexicon.sop', 'calc-words.generated.mjs']) {
    const file = name.endsWith('.mjs') ? join(REPO, 'src/knowledge', name) : join(DIR, name);
    if ((existsSync(file) ? readFileSync(file, 'utf8') : null) === out[name]) continue;
    if (process.argv.includes('--check')) { stale++; console.error(`stale: ${file}`); } else { writeFileSync(file, out[name]); console.log(`written ${file}`); }
  }
  console.log(`${out.frames} frames`);
  if (stale) process.exit(1);
}
