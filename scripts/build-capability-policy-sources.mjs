import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { emit, done } from './lib/generated.mjs';

const folder = new URL('../worlds/app.project/', import.meta.url);
for (const [source, module] of [
  ['reader-context-schema.sop', 'reader-context-schema-source.mjs'],
  ['reader-context-policy.sop', 'reader-context-policy-source.mjs'],
  ['reader-admission-schema.sop', 'reader-admission-schema-source.mjs'],
  ['reader-admission-policy.sop', 'reader-admission-policy-source.mjs'],
  ['scene-default-schema.sop', 'scene-default-schema-source.mjs'],
  ['scene-default-policy.sop', 'scene-default-policy-source.mjs'],
  ['scene-default-projection.sop', 'scene-default-projection-source.mjs'],
  ['capability-policy.sop', 'capability-policy.mjs'],
  ['constructor-policy.sop', 'constructor-policy-source.mjs'],
  ['constructor-schema.sop', 'constructor-schema-source.mjs'],
  ['execution-policy.sop', 'execution-policy-source.mjs'],
  ['execution-policy-schema.sop', 'execution-policy-schema-source.mjs'],
  ['history-policy.sop', 'history-policy-source.mjs'],
  ['history-schema.sop', 'history-schema-source.mjs'],
  ['browser-state-schema.sop', 'browser-state-schema-source.mjs'],
  ['browser-state-bindings.sop', 'browser-state-bindings-source.mjs'],
  ['request-routing-schema.sop', 'request-routing-schema-source.mjs'],
  ['request-routing-policy.sop', 'request-routing-policy-source.mjs'],
  ['query-reading-schema.sop', 'query-reading-schema-source.mjs'],
  ['query-reading-policy.sop', 'query-reading-policy-source.mjs'],
]) {
  const text = readFileSync(new URL(source, folder), 'utf8');
  emit(fileURLToPath(new URL(module, folder)), '// Generated from ' + source + '.\nexport default ' + JSON.stringify(text) + ';\n');
}
// Each SOP area's own files (area.sop, the rule files it names, the shared act schema), for hosts created
// without a loader (tests, inspection, the browser worker).
{
  const { readdirSync, existsSync } = await import('node:fs');
  for (const world of readdirSync(new URL('../worlds/', import.meta.url)).filter((w) => existsSync(new URL('../worlds/' + w + '/area.sop', import.meta.url)))) {
    const area = readFileSync(new URL('../worlds/' + world + '/area.sop', import.meta.url), 'utf8');
    const named = [...area.matchAll(/ file="([^"]+)"/g)].map((m) => m[1]);
    const files = { [world + '/area.sop']: area, 'app.project/act-schema.sop': readFileSync(new URL('../worlds/app.project/act-schema.sop', import.meta.url), 'utf8') };
    for (const file of named) files[world + '/' + file] = readFileSync(new URL('../worlds/' + world + '/' + file, import.meta.url), 'utf8');
    emit(fileURLToPath(new URL('../worlds/' + world + '/area-sources.mjs', import.meta.url)), '// Generated by scripts/build-capability-policy-sources.mjs from the area files it names.\nexport default ' + JSON.stringify(files) + ';\n');
  }
}
done('build-capability-policy-sources');
