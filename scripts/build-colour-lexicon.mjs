// KNOWLEDGE-OUT step 4a: ONE colour lexicon for every world, generated from the knowledge catalog (k.values) through the colour reader (src/knowledge/values.mjs).
//   node scripts/build-colour-lexicon.mjs [<catalog folder>]
// Rewrites `lex.lang.colour` in worlds/lang.common/lexicon.sop: every colour name of the catalog (single words and, with underscores, the names of several words) plus the spellings and shorthand
// the reader accepts. The colour groups of the worlds (art.draw, data.charts, docs.editor, talk, kids.shapes) keep no words: they `extends=$lex.lang.colour`. Without a catalog folder the
// bundled subset (itself generated from the catalog) is used. Run again when the catalog changes; tests/colour-reader.test.mjs fails when the lexicon is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { createFacts } from '../src/knowledge/facts.mjs';
import { createKnowledgeSource } from '../src/loaders/knowledge-source.mjs';
import { loadValues, colourPhrases, colourLexiconWords, basicColourNames } from '../src/knowledge/values.mjs';

const ROOT = path.join(import.meta.dirname, '..');
/** The world colour groups that read the shared lexicon instead of holding words: [world, group]. */
export const SHARED = [['art.draw', 'colors'], ['data.charts', 'colors'], ['docs.editor', 'colors'], ['talk', 'colours'], ['kids.shapes', 'colors']];

/** The text of the shared lexicon block. */
export const colourLexicon = () => `@lex.lang.colour core.lexicon\n    class=noun\n    doc="Colour names of the knowledge catalog (k.values), with their spellings and shorthand: generated by scripts/build-colour-lexicon.mjs, never edited by hand. Worlds extend it."\n${colourLexiconWords().map((w) => `    word=${w.replace(/ /g, '_')}`).join('\n')}\n`;

/** The words of the other lexicon groups of a world (everything that is not the colour group `id`): a colour name that this world already uses as another kind of word (sand and snow are ground covers, a tomato is a thing) is not a colour word here. */
function otherWords(text, id) {
  const groups = new Map();
  let cur = null;
  for (const line of text.split('\n')) {
    const h = /^@(\S+)\s+core\.lexicon/.exec(line);
    if (h) { cur = h[1] === id ? null : []; if (cur) groups.set(h[1], cur); continue; }
    if (line.startsWith('@')) { cur = null; continue; }
    const m = cur ? /^\s+word=(\S+)/.exec(line) : null;
    if (m) cur.push(m[1].toLowerCase());
  }
  const colours = new Set(colourLexiconWords().map((c) => c.replace(/ /g, '_')));
  const out = new Set();
  // a group of mostly colour names (a world that lists the colours again among its modifiers) says nothing about what else a word is
  for (const words of groups.values()) if (words.filter((w) => colours.has(w)).length / (words.length || 1) < 0.3) for (const w of words) out.add(w);
  return out;
}

/** `text` with the group `id` replaced by `block` (the group runs to the next wire or the end). */
function replaceGroup(text, id, block) {
  const start = text.indexOf(`@${id} core.lexicon`);
  if (start < 0) throw new Error(`no group ${id}`);
  const next = text.indexOf('\n@', start + 1);
  return `${text.slice(0, start)}${block}${next < 0 ? '' : text.slice(next + 1)}`;
}

export function build() {
  const files = new Map();
  const edit = (p, f) => { const full = path.join(ROOT, p); files.set(full, f(files.get(full) ?? readFileSync(full, 'utf8'))); };
  edit('worlds/lang.common/lexicon.sop', (t) => replaceGroup(t, 'lex.lang.colour', `${colourLexicon()}\n`));
  for (const [w, g] of SHARED) {
    edit(`worlds/${w}/lexicon.sop`, (t) => {
      const id = `lex.${w}.${g}`, old = t.slice(t.indexOf(`@${id} core.lexicon`));
      const cls = /class=(\w+)/.exec(old)?.[1] ?? 'noun', doc = (/doc="([^"]*)"/.exec(old.split('\n@')[0])?.[1] ?? 'Colour names').replace(/: the shared lexicon.*$/, '');
      const basic = new Set(basicColourNames()), others = otherWords(t, id);
      const exclude = colourLexiconWords().map((c) => c.replace(/ /g, '_')).filter((c) => others.has(c) && !basic.has(c.replace(/_/g, ' ')));
      return replaceGroup(t, id, `@${id} core.lexicon\n    class=${cls}\n    doc="${doc}: the shared lexicon of colour names (lex.lang.colour, from k.values)"\n    extends=$lex.lang.colour\n${exclude.map((c) => `    exclude=${c}\n`).join('')}\n`);
    });
  }
  return files;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  if (process.argv[2]) await loadValues(createFacts({ source: createKnowledgeSource(process.argv[2]) }));
  for (const [p, t] of build()) writeFileSync(p, t);
  console.log(`lex.lang.colour: ${colourLexiconWords().length} words (of ${colourPhrases().length} the reader knows); ${SHARED.length} world groups extend it`);
}
