// Builds worlds/ui.avatar/default-face.mjs: the default preset of k.faces only (one variant for each slot it uses, the colours, the slot boxes and aliases), generated from the
// catalog so that the Avatar tab always has a face on a first visit with no network. It is data from k.faces (CC0-1.0), not a hand copy; run again when the catalog changes:
//   node scripts/build-default-face.mjs <catalog folder (docs/worlds of sop-knowledge-worlds)> [preset]
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { createFacts } from '../src/knowledge/facts.mjs';
import { createKnowledgeSource } from '../src/loaders/knowledge-source.mjs';

const dir = process.argv[2], want = process.argv[3] ?? 'girl';
if (!dir) { console.error('usage: node scripts/build-default-face.mjs <catalog folder> [preset]'); process.exit(1); }
const data = await createFacts({ source: createKnowledgeSource(dir) }).faces();
if (!data?.presets[want]) { console.error(`no preset ${want} in ${dir}`); process.exit(1); }
const p = data.presets[want];
// Everything the avatar needs to work with no network: EVERY slot (with its aliases), every preset and expression (so "an angry boy" is understood), the colours, and for each
// slot every variant that a preset or an expression names, else its first variant; a slot is always removable ("none"). The catalog adds the other variants once it is loaded.
const used = new Map();
const use = (slot, name) => { if (name) (used.get(slot) ?? used.set(slot, new Set()).get(slot)).add(name); };
for (const pr of Object.values(data.presets)) for (const [slot, name] of Object.entries(pr.slots)) use(slot, name);
for (const e of Object.values(data.expressions ?? {})) for (const [slot, name] of Object.entries(e.slots ?? e)) if (typeof name === 'string') use(slot, name);
const out = {
  ...data,
  slots: data.slots.map((s) => {
    const keep = s.variants.filter((v) => used.get(s.name)?.has(v.name) || v.name === p.slots[s.name]);
    return { ...s, variants: keep.length ? keep : s.variants.slice(0, 1) };
  }),
};
const text = `// SPDX-License-Identifier: AGPL-3.0-only\n// GENERATED by scripts/build-default-face.mjs from the catalog k.faces (all slots, presets and expressions; default preset "${want}", CC0-1.0): do not edit by hand.\n// The face the avatar shows when the catalog cannot be reached (first visit, offline).\nexport const DEFAULT_FACE = ${JSON.stringify(out)};\n`;
writeFileSync(path.join(import.meta.dirname, '../worlds/ui.avatar/default-face.mjs'), text);
console.log(`default-face.mjs: preset ${want}, ${text.length} bytes`);
