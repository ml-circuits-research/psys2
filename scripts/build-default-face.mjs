// Builds worlds/ui.avatar/default-face.mjs: the default preset of k.faces only (one variant for each slot it uses, the colours, the slot boxes and aliases), generated from the
// catalog so that the Avatar tab always has a face on a first visit with no network. It is data from k.faces (CC0-1.0), not a hand copy; run again when the catalog changes:
//   node scripts/build-default-face.mjs <catalog folder (docs/worlds of sop-knowledge-worlds)> [preset]
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { createFacts } from '../src/knowledge/facts.mjs';
import { createKnowledgeSource } from '../src/loaders/knowledge-source.mjs';

const dir = process.argv[2], want = process.argv[3] ?? 'girl';
if (!dir) { console.error('usage: node scripts/build-default-face.mjs <catalog folder> [preset]'); process.exit(1); }
const data = await createFacts({ source: createKnowledgeSource(dir) }).faces();
if (!data?.presets[want]) { console.error(`no preset ${want} in ${dir}`); process.exit(1); }
const p = data.presets[want];
const out = {
  ...data, presets: { [want]: p }, expressions: {},
  slots: data.slots.map((s) => ({ ...s, variants: s.variants.filter((v) => v.name === p.slots[s.name]) })),
};
// a slot the preset leaves empty keeps one variant so that it can be put on
for (const s of out.slots) if (!s.variants.length) s.variants = [data.slots.find((x) => x.name === s.name).variants[0]];
const text = `// SPDX-License-Identifier: AGPL-3.0-only\n// GENERATED by scripts/build-default-face.mjs from the catalog k.faces (preset "${want}", CC0-1.0): do not edit by hand.\n// The face the avatar shows when the catalog cannot be reached (first visit, offline).\nexport const DEFAULT_FACE = ${JSON.stringify(out)};\n`;
writeFileSync(path.join(import.meta.dirname, '../worlds/ui.avatar/default-face.mjs'), text);
console.log(`default-face.mjs: preset ${want}, ${text.length} bytes`);
