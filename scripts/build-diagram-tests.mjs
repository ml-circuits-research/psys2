// Writes worlds/diagram.sketch/tests.sop (task DIAG): the tests of the world, made from the data of diagram-vss-demo.
//   node scripts/build-diagram-tests.mjs
//   1. per action and per question kind, up to 6 sentences of data/bench (gold args): each runs in a fresh session after one setup message that draws the
//      row's shapes; a case is kept only when our rules read it as the gold act AND the engine's rules reader reads the gold args (bench-canon `score`);
//      the reply and the state (shapes, connections) it left are pinned.
//   2. the example sessions data/examples/manual.json (reviewed reference programs): the sentences of a scenario run in one session on the Diagram tab,
//      after every turn the shapes and connections must be the ones the reference program makes (the engine replays the reference SOP);
//      a scenario is kept as far as our world agrees with the reference.
// Every test is a regression test of what the world does now AND agrees with the gold of the source data.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createFsLoader, DEFAULT_ROOT } from '../src/loaders/fs-loader.mjs';
import { createEngine } from '../src/dialog/index.mjs';
import { score } from '../imports/diagram-vss-demo/reference/bench-canon.js';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DATA = join(REPO, 'imports/diagram-vss-demo/data');
const WORLD = 'diagram.sketch';
const q = (s) => JSON.stringify(String(s));
const engine = await createEngine({ loader: createFsLoader({ roots: [DEFAULT_ROOT] }) });
const ops = await import('../worlds/diagram.sketch/engine.mjs');
const K = ops.kit();
const allActs = new Map(engine.set.list().flatMap((w) => w.patterns.map((p) => [p.id, /action=([\w.]+)/.exec(p.emit ?? '')?.[1] ?? null])));
const actOfGold = (type, a) => (type === 'question' ? `diagram.ask.${a.ask}` : type === 'fact' ? 'diagram.fact' : type === 'rule' ? 'diagram.rule' : `diagram.${a.action}`).toLowerCase();
const PER_ACT = 6;

const out = ['@gen.diagram.sketch.tests.note core.note', `    text="Generated by scripts/build-diagram-tests.mjs from data/bench and data/examples of diagram-vss-demo (commit 9900d34): every test is checked against the gold of the source data when it is written. Do not edit by hand."`, ''];
let nTests = 0;
const counts = {};
const add = (id, session, input, expects, states) => {
  out.push(`@t.diagram.sketch.${id} core.test`, `    input=${q(input)}`);
  for (const e of expects) out.push(`    expect=${q(e)}`);
  for (const s of states) out.push(`    expectState=${q(s)}`);
  out.push(`    session=${session}`, '');
  nTests++;
};
const shot = (r) => { const t = (r.answers.at(-1)?.text ?? r.text ?? '').replace(/\s+/g, ' ').trim(); return t.length > 60 ? t.slice(0, 60).replace(/\s+\S*$/, '') : t; };
const withText = (t) => (/[“”"]/.test(t) ? null : t);

// ---- 1. bench ----------------------------------------------------------------------------------------------------------------------
const rows = [];
for (const id of ['hand', 'blind', 'broad', 'heldout_formulations', 'seen', 'new_identities']) {
  for (const r of JSON.parse(readFileSync(join(DATA, 'bench', `${id}.json`), 'utf8'))) if (r.gold && r.type && (r.names ?? []).length <= 6) rows.push({ ...r, set: id });
}
// when the bench has fewer than PER_ACT clean cases of an act, short spans of the labelled training messages (gold args of the wire) fill up
const walk = (d) => readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(join(d, e.name)) : [join(d, e.name)]));
const filler = [];
for (const f of walk(join(DATA, 'train')).filter((x) => x.endsWith('.jsonl')).sort()) {
  for (const line of readFileSync(f, 'utf8').split('\n')) {
    if (!line.trim()) continue;
    let m; try { m = JSON.parse(line); } catch { continue; }
    if (!m.wires || (m.names ?? []).length > 6) continue;
    for (const w of m.wires) if (w.args && w.span && w.span.length <= 70 && w.span.length >= 6 && !/\$new/.test(JSON.stringify(w.args))) filler.push({ text: w.span.trim(), names: m.names ?? [], type: w.type, gold: w.args, groups: m.groups ?? {}, set: 'train' });
  }
}
const byAct = new Map();
for (const r of rows) { const a = actOfGold(r.type, r.gold); (byAct.get(a) ?? byAct.set(a, []).get(a)).push(r); }
for (const r of filler) { const a = actOfGold(r.type, r.gold); (byAct.get(a) ?? byAct.set(a, []).get(a)).push(r); }
for (const [act, list] of [...byAct].sort()) {
  const seen = new Set();
  let kept = 0;
  for (const r of list) {
    if (kept >= PER_ACT) break;
    if (seen.has(r.text.toLowerCase())) continue;
    seen.add(r.text.toLowerCase());
    const names = r.names ?? [];
    const groups = Object.entries(r.groups ?? {}).filter(([, mem]) => mem.length >= 2 && mem.every((x) => names.includes(x))).map(([name, members]) => ({ name, members }));
    const state = { groups, shapes: names.map((name, i) => ({ name, shape: 'circle', x: 80 + 100 * i, y: 80, size: 62, color: 'white', order: i + 1 })), seq: {}, edgeSeq: 0, order: names.length };
    const nodes = ops.read(r.text, state)?.nodes ?? [];
    if (!score(nodes, { type: r.type, gold: r.gold }).ok) continue;
    // run: setup message, then the case
    const s = engine.createSession({ language: 'en' });
    const setup = names.length ? `Draw ${names.map((n) => `a circle called ${n}`).join(', ')}.` : null;
    const setup2 = groups.map((g) => `Please group ${g.members.join(', ')} as ${g.name}.`);
    if (setup) { const rs = await s.send(setup, { language: 'en' }); for (const g2 of setup2) await s.send(g2, { language: 'en' }); if (s.state(WORLD).shapes?.length !== names.length || (s.state(WORLD).groups ?? []).length !== groups.length) continue; void rs; }
    const reply = await s.send(r.text, { language: 'en' });
    const seg = reply.segments.find((x) => x.match && x.match.worldId === WORLD);
    if (!seg || (allActs.get(seg.match.patternId) ?? '').toLowerCase() !== act) continue;
    const st = s.state(WORLD);
    const key = `${act.replace(/^diagram\./, '').replace(/\./g, '_')}.k${String(kept + 1).padStart(2, '0')}`;
    if (setup) add(`b.${key}.a`, `b.${key}`, setup, [`Drew `], [`shapes.length=${names.length}`]);
    setup2.forEach((g2, gi) => add(`b.${key}.a${gi + 2}`, `b.${key}`, g2, [`Grouped`], [`groups.length=${gi + 1}`]));
    add(`b.${key}.b`, `b.${key}`, r.text, [shot(reply)].filter(Boolean), [`shapes.length=${st.shapes.length}`, `edges.length=${st.edges.length}`]);
    kept++;
  }
  counts[act] = kept;
}

// ---- 2. example sessions -------------------------------------------------------------------------------------------------------------
const manual = JSON.parse(readFileSync(join(DATA, 'examples/manual.json'), 'utf8')).scenarios;
const scen = {};
const P = { circle: 'c', rectangle: 'r', square: 's', diamond: 'd', ellipse: 'e', triangle: 't', hexagon: 'h', star: 'k', text: 'x' };
const short = (n) => n.replace(/^(circle|rectangle|square|diamond|ellipse|triangle|hexagon|star|text)(\d+)$/, (m, k, d) => P[k] + d);   // the source names an unnamed shape circle1, the world c1
for (const [name, turns] of Object.entries(manual)) {
  const ref = K.createSystem();
  const s = engine.createSession({ language: 'en' });
  await s.send('open the diagram tab', { language: 'en' });
  if (s.state('ui.shell').activeTab !== 'diagram') throw new Error('open the diagram tab does not open the Diagram tab');
  let agreed = 0;
  const lines = [];
  for (const [i, t] of turns.entries()) {
    try { ref.engine.run(K.parse(t.sop)); } catch { break; }
    const want = { shapes: ref.world.state.shapes.length, edges: ref.world.state.edges.length, names: ref.world.state.shapes.map((x) => short(x.name)).sort().join(',') };
    const reply = await s.send(t.text, { language: 'en' });
    const st = s.state(WORLD);
    const got = { shapes: st.shapes.length, edges: st.edges.length, names: st.shapes.map((x) => x.name).sort().join(',') };
    if (got.shapes !== want.shapes || got.edges !== want.edges || got.names !== want.names) break;
    agreed = i + 1;
    lines.push({ text: t.text, shapes: got.shapes, edges: got.edges, reply: shot(reply) });
  }
  scen[name] = { turns: turns.length, agreed };
  add(`ex.${name}.n000`, `ex.${name}`, 'open the diagram tab', [], ['ui.shell:activeTab=diagram']);
  lines.forEach((l, i) => add(`ex.${name}.n${String(i + 1).padStart(3, '0')}`, `ex.${name}`, l.text, [], [`shapes.length=${l.shapes}`, `edges.length=${l.edges}`]));
}
writeFileSync(join(REPO, 'worlds/diagram.sketch/tests.sop'), `${out.join('\n')}\n`);
console.log(JSON.stringify({ tests: nTests, per_act: counts, scenarios: scen }, null, 1));
