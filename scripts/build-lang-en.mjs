/**
 * Writes src/lang/en.facts.generated.mjs: the bundled copy of the catalog world `w.lang.en` (sop-knowledge-worlds, docs/worlds/w.lang.en) that src/lang/en.mjs reads when the catalog is not (yet) reachable: the first paint,
 * the offline host, the tests. GENERATED FROM THE CATALOG, never from a copy kept here: the catalog is the source of truth for English (English as a world, questions.md Q10), edit it there and run this again.
 * The shards are the ones the readers use (`LANG_EN_SHARDS` of src/lang/en.mjs); of them only the types the readers and the library grammar use are bundled, without `core.source`, `doc` and `note`
 * (phrases, constructions and role maps are the catalog's documentation of English, not read at run time; a lexicon keeps its name, the frames only need to know which lexicons are shared).
 *
 *   node scripts/build-lang-en.mjs <catalog folder (docs/worlds of sop-knowledge-worlds)> [--check]
 *   (the folder may also come from PSYS2_KNOWLEDGE; --check compares the bundle with the catalog and exits 1 when it is stale)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LANG_EN_SHARDS } from '../src/lang/en.mjs';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const NOT_READ = new Set(['w.lang.en.phrase', 'w.lang.en.role_map']);
const QUOTED = '"(?:[^"\\\\]|\\\\.)*"';
const DROP = new RegExp(`\\s(?:core\\.source|doc|note)=(?:${QUOTED}|\\S+)`, 'g');
const ITEMS = new RegExp(`\\s(?:item|group)=(?:${QUOTED}|\\S+)`, 'g');

/** The text of one shard as the bundle keeps it: comments and blank lines out, the types that are not read out, the documentation attributes out. */
export function strip(text) {
  return `${text.split('\n').filter((l) => l.startsWith('@')).filter((l) => !NOT_READ.has(l.split(/\s+/)[1])).map((l) => (l.split(/\s+/)[1] === 'w.lang.en.lex' ? l.replace(DROP, '').replace(ITEMS, '') : l.replace(DROP, ''))).join('\n')}\n`;
}

export function render(catalog) {
  const texts = Object.fromEntries(LANG_EN_SHARDS.map((s) => [s, strip(readFileSync(join(catalog, 'w.lang.en/shards', `${s}.sop`), 'utf8'))]));
  // lexicon names live in phrases.sop: the frames name them (`lexicon=`), and a shared one is written `lex.<name>` in a pattern
  texts.lexicons = strip(readFileSync(join(catalog, 'w.lang.en/shards/phrases.sop'), 'utf8').split('\n').filter((l) => l.split(/\s+/)[1] === 'w.lang.en.lex').join('\n'));
  const index = JSON.parse(readFileSync(join(catalog, 'index.json'), 'utf8')).worlds.find((w) => w.id === 'w.lang.en');
  return `// GENERATED by scripts/build-lang-en.mjs from the catalog world w.lang.en (version ${index?.version ?? '?'}, shards ${LANG_EN_SHARDS.join(', ')}). Never edited by hand.\n// SPDX-License-Identifier: CC0-1.0 (the catalog's licence of w.lang.en)\nexport const LANG_EN_FACTS = ${JSON.stringify(texts, null, 1)};\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const catalog = process.argv.slice(2).find((a) => !a.startsWith('--')) ?? process.env.PSYS2_KNOWLEDGE;
  if (!catalog) { console.error('usage: node scripts/build-lang-en.mjs <catalog folder (docs/worlds)> [--check]'); process.exit(1); }
  const out = join(REPO, 'src/lang/en.facts.generated.mjs');
  const text = render(resolve(catalog));
  if (process.argv.includes('--check')) {
    let cur = ''; try { cur = readFileSync(out, 'utf8'); } catch { /* missing */ }
    if (cur !== text) { console.error('src/lang/en.facts.generated.mjs is stale: run node scripts/build-lang-en.mjs <catalog>'); process.exit(1); }
  } else writeFileSync(out, text);
}
