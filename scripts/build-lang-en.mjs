/**
 * Writes src/lang/en.facts.generated.mjs: the bundled copy of the catalog world `w.lang.en` (sop-knowledge-worlds, docs/worlds/w.lang.en) that src/lang/en.mjs reads when the catalog is not (yet) reachable: the first paint,
 * the offline host, the tests. GENERATED FROM THE CATALOG, never from a copy kept here: the catalog is the source of truth for English (English as a world, questions.md Q10), edit it there and run this again.
 * The shards are the ones the readers use (`LANG_EN_SHARDS` of src/lang/en.mjs); of them only the types the readers and the library grammar use are bundled, without `core.source`, `doc` and `note`
 * (phrases, constructions and role maps are the catalog's documentation of English, not read at run time; a lexicon keeps its name, the frames only need to know which lexicons are shared).
 *
 *   node scripts/build-lang-en.mjs [<catalog folder (docs/worlds of sop-knowledge-worlds)>] [--check]
 *   (no folder: the catalog at the pin, src/knowledge/catalog-pin.mjs, checked out by scripts/lib/catalog-pin.mjs (P4), and the header names the commit; a folder given or
 *   PSYS2_KNOWLEDGE is read as is; --check compares the bundle with the catalog and exits 1 when it is stale; `npm run check:catalog` runs it)
 *
 * ONE COMMAND: the generated schema worlds (the schema.sop of every world folder under worlds and tests/fixtures/worlds: lexicon, patterns, operations, templates, ops.mjs) are generated from the frames of this bundle, so after the bundle is
 * written every one of them is regenerated by scripts/build-schema-world.mjs (a fresh process, which reads the new bundle); with --check each is checked for staleness too. `--no-schemas` skips this.
 * Before them the bundled subsets of the same catalog are rebuilt (or checked) by the scripts of CATALOG_BUNDLES (src/knowledge/bundled-*.mjs, worlds/acts verbs, the default face;
 * each names the catalog commit in its header); `--no-bundles` skips this.
 * (the meta.worlds cards are built at run time from the same schemas: nothing to write.) `npm run build:lang -- <catalog folder>` is the same command.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LANG_EN_SHARDS } from '../src/lang/en.mjs';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');
/** The scripts that bundle the rest of the catalog (each takes the same catalog folder, or none for the pin, and --check). build-bundled-subset runs build-bundled-geo,
 * build-acts-lexicon and build-default-face itself; build-bundled-names reads the animals bundle the subset writes, so it comes after it. */
export const CATALOG_BUNDLES = ['build-bundled-subset.mjs', 'build-bundled-request.mjs', 'build-bundled-names.mjs', 'build-bundled-compose.mjs', 'build-bundled-diagrams.mjs', 'build-bundled-genres.mjs', 'build-bundled-interest.mjs', 'build-bundled-person.mjs', 'build-lang-ro.mjs'];
const NOT_READ = new Set(['w.lang.en.phrase', 'w.lang.en.role_map']);
const QUOTED = '"(?:[^"\\\\]|\\\\.)*"';
const DROP = new RegExp(`\\s(?:core\\.source|doc|note)=(?:${QUOTED}|\\S+)`, 'g');
const ITEMS = new RegExp(`\\s(?:item|group)=(?:${QUOTED}|\\S+)`, 'g');

/** The text of one shard as the bundle keeps it: comments and blank lines out, the types that are not read out, the documentation attributes out. */
export function strip(text) {
  return `${text.split('\n').filter((l) => l.startsWith('@')).filter((l) => !NOT_READ.has(l.split(/\s+/)[1])).map((l) => (l.split(/\s+/)[1] === 'w.lang.en.lex' ? l.replace(DROP, '').replace(ITEMS, '') : l.replace(DROP, ''))).join('\n')}\n`;
}

export function render(catalog, commit = null) {
  const texts = Object.fromEntries(LANG_EN_SHARDS.map((s) => [s, strip(readFileSync(join(catalog, 'w.lang.en/shards', `${s}.sop`), 'utf8'))]));
  // lexicon names live in phrases.sop: the frames name them (`lexicon=`), and a shared one is written `lex.<name>` in a pattern
  texts.lexicons = strip(readFileSync(join(catalog, 'w.lang.en/shards/phrases.sop'), 'utf8').split('\n').filter((l) => l.split(/\s+/)[1] === 'w.lang.en.lex').join('\n'));
  const index = JSON.parse(readFileSync(join(catalog, 'index.json'), 'utf8')).worlds.find((w) => w.id === 'w.lang.en');
  return `// GENERATED by scripts/build-lang-en.mjs from the catalog world w.lang.en (version ${index?.version ?? '?'}${commit ? `, catalog commit ${commit}` : ''}, shards ${LANG_EN_SHARDS.join(', ')}). Never edited by hand.\n// SPDX-License-Identifier: CC0-1.0 (the catalog's licence of w.lang.en)\nexport const LANG_EN_FACTS = ${JSON.stringify(texts, null, 1)};\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  let catalog = process.argv.slice(2).find((a) => !a.startsWith('--')) ?? process.env.PSYS2_KNOWLEDGE, commit = null;
  if (!catalog) { const { pinnedCatalog } = await import('./lib/catalog-pin.mjs'); const p = pinnedCatalog(); catalog = p.dir; commit = p.commit; }
  const out = join(REPO, 'src/lang/en.facts.generated.mjs');
  const text = render(resolve(catalog), commit);
  if (process.argv.includes('--check')) {
    let cur = ''; try { cur = readFileSync(out, 'utf8'); } catch { /* missing */ }
    if (cur !== text) { console.error('src/lang/en.facts.generated.mjs is stale: run node scripts/build-lang-en.mjs <catalog>'); process.exit(1); }
  } else writeFileSync(out, text);
  // the bundled subsets of the same catalog (P4, reviewer 2026-11-15 02:05 item 3): every bundled-*.mjs, the act verbs, the default face; before the schema worlds, which read the act verbs
  if (!process.argv.includes('--no-bundles')) {
    const given = process.argv.slice(2).find((a) => !a.startsWith('--'));
    let bad = 0;
    for (const script of CATALOG_BUNDLES) {
      const r = spawnSync(process.execPath, [join(REPO, 'scripts', script), ...(given ? [given] : []), ...(process.argv.includes('--check') ? ['--check'] : [])], { encoding: 'utf8' });
      if (r.status) { bad++; console.error(`${script}: ${(r.stderr || r.stdout).trim().split('\n').filter((l) => /stale|rror/.test(l)).join('; ') || 'failed'}`); }
    }
    console.log(`${CATALOG_BUNDLES.length} bundle scripts ${process.argv.includes('--check') ? 'checked' : 'run'}${bad ? `, ${bad} ${process.argv.includes('--check') ? 'stale' : 'failed'}` : ''}`);
    if (bad) process.exit(1);
  }
  if (!process.argv.includes('--no-schemas')) {
    const dirs = ['worlds', 'tests/fixtures/worlds'].flatMap((base) => (existsSync(join(REPO, base)) ? readdirSync(join(REPO, base)).map((d) => join(REPO, base, d)) : [])).filter((d) => existsSync(join(d, 'schema.sop')));
    let bad = 0;
    for (const d of dirs) {
      const r = spawnSync(process.execPath, [join(REPO, 'scripts/build-schema-world.mjs'), d, ...(process.argv.includes('--check') ? ['--check'] : [])], { encoding: 'utf8' });
      if (r.status) { bad++; console.error(`schema world ${d}: ${(r.stderr || r.stdout).trim().split('\n')[0]}`); }
    }
    console.log(`${dirs.length} schema worlds ${process.argv.includes('--check') ? 'checked' : 'regenerated'}${bad ? `, ${bad} ${process.argv.includes('--check') ? 'stale' : 'failed'}` : ''}`);
    if (bad) process.exit(1);
  }
}
