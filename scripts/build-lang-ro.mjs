/**
 * Writes src/lang/ro.facts.generated.mjs: the bundled copy of the catalog's language world `w.lang.ro` (sop-knowledge-worlds, docs/worlds/w.lang.ro) that src/lang/ro.mjs reads when Romanian is
 * the selected language (first paint, offline, tests). GENERATED FROM THE CATALOG, never edited here (the same rule as src/lang/en.facts.generated.mjs): schema and shards without comments and
 * `core.source`, the dictionary as one text per first letter. Romanian words are DATA of the language world (the only world that may hold them). The module is imported lazily: only a
 * session whose language is Romanian loads its 150 kB.
 *
 *   node scripts/build-lang-ro.mjs <catalog folder (docs/worlds of sop-knowledge-worlds)> [--check]
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(REPO, 'src/lang/ro.facts.generated.mjs');
const catalog = process.argv[2] ?? process.env.PSYS2_KNOWLEDGE;
if (!catalog) { console.error('usage: node scripts/build-lang-ro.mjs <catalog folder> [--check]'); process.exit(1); }
const QUOTED = '"(?:[^"\\\\]|\\\\.)*"';
const DROP = new RegExp(`\\s(?:core\\.source|doc|note)=(?:${QUOTED}|\\S+)`, 'g');
const dir = join(catalog, 'w.lang.ro');
const wires = ['schema.sop', ...readdirSync(join(dir, 'shards')).sort().map((f) => `shards/${f}`)].map((f) => readFileSync(join(dir, f), 'utf8').split('\n').filter((l) => l.startsWith('@')).map((l) => l.replace(DROP, '')).join('\n')).join('\n');
const dictionary = {};
for (const f of readdirSync(join(dir, 'dictionary')).filter((x) => x.endsWith('.tsv')).sort()) dictionary[f[0]] = readFileSync(join(dir, 'dictionary', f), 'utf8').split('\n').filter((l) => l.trim() && !l.startsWith('#')).join('\n');
const text = `// SPDX-License-Identifier: AGPL-3.0-only\n// GENERATED by scripts/build-lang-ro.mjs from the knowledge catalog's world w.lang.ro (CC0-1.0, hand-core): do not edit by hand. Romanian words are data of the language world.\n// Loaded lazily, only when Romanian is the selected language (src/lang/ro.mjs).\nexport const LANG_RO_FACTS = ${JSON.stringify({ wires, dictionary })};\n`;
if (process.argv.includes('--check')) { let cur = ''; try { cur = readFileSync(OUT, 'utf8'); } catch { /* none */ } if (cur !== text) { console.error('src/lang/ro.facts.generated.mjs is stale'); process.exit(1); } console.log('up to date'); } else { writeFileSync(OUT, text); console.log(`wrote ${OUT}: ${text.length} bytes`); }
