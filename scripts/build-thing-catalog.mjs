/**
 * Builds the thing catalog the drawing board draws from facts (spec 07 section 7).
 *   node scripts/build-thing-catalog.mjs [--check]
 * Reads knowledge/k.objects/shards/*.sop (the hand-written shards of sop-knowledge-worlds, format of its k.objects world: an object is a list of parts, each with a
 * primitive shape, a box x y w h in the object's 0-100 frame, a draw order z, a colour, and its points as separate wires) and knowledge/k.objects/vocab.json
 * (lemma -> shards, the catalog index shared with KNOWLEDGE-BY-LOOKUP), and writes worlds/art.draw/things.catalog.mjs: plain data, so that the world's modules
 * stay browser-safe and need no file loader. `--check` only reports whether the generated file is up to date.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SHARDS = join(ROOT, 'knowledge/k.objects/shards');
const OUT = join(ROOT, 'worlds/art.draw/things.catalog.mjs');
const KIND_SHARD = join(ROOT, 'knowledge/art.draw.kinds/shards/kinds.sop');

const unq = (t) => (t.startsWith('"') ? JSON.parse(t) : t);
/** `@id type key=value key=value "quoted value"` -> { id, type, attrs: { key: [values] } } */
export function parseLine(line) {
  const m = /^@(\S+)\s+(\S+)\s*(.*)$/.exec(line);
  if (!m) return null;
  const attrs = {};
  for (const t of m[3].matchAll(/([A-Za-z_.]+)=("(?:[^"\\]|\\.)*"|\S+)/g)) (attrs[t[1]] ??= []).push(unq(t[2]));
  return { id: m[1], type: m[2], attrs };
}
const num = (a, k) => Number(a[k][0]);

export function readShard(text) {
  const objects = new Map(), points = new Map(), words = {}, order = [];
  for (const line of text.split('\n')) {
    if (!line.startsWith('@')) continue;
    const w = parseLine(line);
    if (!w) continue;
    if (w.type === 'k.objects.object') objects.set(w.attrs.name[0], []);
    else if (w.type === 'k.objects.part') {
      const a = w.attrs, p = { name: a.name[0], shape: a.shape[0], x: num(a, 'x'), y: num(a, 'y'), w: num(a, 'w'), h: num(a, 'h'), z: num(a, 'z'), colour: a.colour ?? ['grey'] };
      if (a.kind) p.kind = a.kind[0];
      if (a.rgb) p.rgb = a.rgb[0];
      if (a.pointing) p.pointing = a.pointing[0];
      if (a.opens) p.opens = a.opens[0];
      p.id = w.id; p.of = a.of[0]; order.push(p);
    } else if (w.type === 'k.objects.point') {
      const key = w.attrs.part[0].replace(/^\$/, '');
      if (!points.has(key)) points.set(key, []);
      points.get(key).push({ n: num(w.attrs, 'n'), x: num(w.attrs, 'x'), y: num(w.attrs, 'y') });
    } else if (w.type === 'core.word' && w.attrs.of?.[0] === 'k.objects.object.name') {
      for (const t of w.attrs.text ?? []) words[t] = w.attrs.means[0];
    }
  }
  for (const p of order) {
    const pts = (points.get(p.id) ?? []).sort((a, b) => a.n - b.n).map((q) => [q.x, q.y]);
    if (pts.length) p.points = pts;
    const { id, of, ...rest } = p;
    (objects.get(of) ?? objects.set(of, []).get(of)).push(rest);
  }
  for (const list of objects.values()) list.sort((a, b) => a.z - b.z);
  return { objects, words };
}

export function build() {
  const things = {}, words = {}, shardOf = {};
  for (const f of readdirSync(SHARDS).filter((x) => x.endsWith('.sop')).sort()) {
    const { objects, words: ws } = readShard(readFileSync(join(SHARDS, f), 'utf8'));
    for (const [name, parts] of objects) { things[name] = parts; shardOf[name] = `k.objects/shards/${f.replace(/\.sop$/, '')}`; }
    Object.assign(words, ws);
  }
  for (const name of Object.keys(things)) words[name] ??= name;
  const vocabFile = join(ROOT, 'knowledge/k.objects/vocab.json');
  const vocab = existsSync(vocabFile) ? JSON.parse(readFileSync(vocabFile, 'utf8')) : {};
  const kindThings = existsSync(KIND_SHARD) ? Object.fromEntries([...readShard(readFileSync(KIND_SHARD, 'utf8')).objects]) : {};
  const sorted = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));
  const body = `// SPDX-License-Identifier: AGPL-3.0-only
// GENERATED by scripts/build-thing-catalog.mjs from knowledge/k.objects (do not edit). The drawable things of the catalog: an object is a list of parts (primitive
// shape, box x y w h in the object's 0-100 frame, draw order z, colour names, points of lines and polygons); THING_WORDS maps a spoken lemma to the object it means;
// THING_SHARD says which shard of the catalog holds the object (the lookup index of KNOWLEDGE-BY-LOOKUP).
export const THINGS = ${JSON.stringify(sorted(things))};
export const THING_WORDS = ${JSON.stringify(sorted(words))};
export const THING_SHARD = ${JSON.stringify(sorted(shardOf))};
// KIND_THINGS: the built-in kinds of the board described as facts of the same format (knowledge/art.draw.kinds).
export const KIND_THINGS = ${JSON.stringify(sorted(kindThings))};
export const THING_VOCAB_SIZE = ${Object.keys(vocab).length};
`;
  return body;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const body = build();
  if (process.argv.includes('--check')) {
    const same = existsSync(OUT) && readFileSync(OUT, 'utf8') === body;
    console.log(same ? 'things.catalog.mjs is up to date' : 'things.catalog.mjs is STALE: run node scripts/build-thing-catalog.mjs');
    process.exit(same ? 0 : 1);
  }
  writeFileSync(OUT, body);
  console.log(`wrote ${OUT}`);
}
