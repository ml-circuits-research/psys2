/**
 * The readings of time.calendar from the PUBLISHED catalog (kids plan, ADR-011; Q18 K7 clock words, L2): writes worlds/time.calendar/lexicon.sop from the lexicons of the shard
 * time-frames of w.lang.en (derived by the catalog from k.time: weekdays, months, seasons, clock phrases, named hours) with the short forms k.time gives as `core.word`
 * (Mon, Feb, fall), and the part of worlds/time.calendar/patterns.sop below the GENERATED marker from the frames of the same shard (the statements of today, the month,
 * the season and the clock; the questions of the day, the date, the time and the month). No phrasing is written here: a frame's words are the catalog's, its pattern is
 * rebuilt by src/lang/en.mjs (createLangEn). The hand part above the marker (the world's reader patterns) is kept as it is.
 *
 *   node scripts/build-time-world.mjs [<catalog docs/worlds dir>] [--check]      (no folder: the catalog at the pin, scripts/lib/catalog-pin.mjs)
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createLangEn } from '../src/lang/en.mjs';
import { parse } from '../src/soplang/index.mjs';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const NS = 'time.calendar';
const DIR = join(REPO, 'worlds', NS);
export const MARKER = '# ---- GENERATED below this line by scripts/build-time-world.mjs from the catalog (w.lang.en shard time-frames). Never edited by hand.';
/** The lexicons of the frames, as world lexicons (`lex.time.<name>` of the catalog -> `lex.time.calendar.<name>`). The hours are numbers to the patterns (`{hour:number}`): the
 *  operations check that the number is an hour of the clock and refuse one that is not ("30 o'clock"), so the catalog's digit items are not lexicon words. */
const LEXICONS = ['weekday', 'month', 'season', 'clock_phrase', 'hour.named'];
/** The k.time types whose `core.word` short forms are spellings of a lexicon's items. */
const SHORT = { weekday: 'k.time.weekday.name', month: 'k.time.month.name', season: 'k.time.season.name' };
/** The frames whose catalog example is the canonical sentence of an operation (help and "Did you mean" quote canonical sentences only, RD6). */
const CANONICAL = new Set(['today', 'ask.time']);

const q = (s) => JSON.stringify(String(s));
const lexId = (n) => `lex.${NS}.${n.replace(/\./g, '_')}`;
const us = (s) => String(s).toLowerCase().replace(/[\s-]+/g, '_');

function expand(match) {
  let m = match.replace(/\bL\b/g, '[$lang.lead.polite]?').replace(/\bD\b/g, '[$acts.det]?');
  m = m.replace(/\{(\w+):lex\.time\.hour(\?)?\}/g, '{$1:number$2}').replace(/\[([^\]]*)\bo_clock\b/g, "[$1o'clock|o_clock");   // the tokenizer keeps "o'clock" one word
  for (const n of LEXICONS) m = m.split(`lex.time.${n}}`).join(`${lexId(n)}}`).split(`lex.time.${n}?}`).join(`${lexId(n)}?}`);
  return `[$lang.lead.filler]? ${m} [$lang.tail.filler|please]?`;
}

export function build(catalog) {
  const shard = readFileSync(join(catalog, 'w.lang.en/shards/time-frames.sop'), 'utf8');
  const lang = createLangEn({ 'time-frames': shard }, null);
  const wires = parse(shard).wires;
  const str = (w, k) => w.entries.filter((e) => e.key === k).map((e) => String(e.value.v));
  const commit = (() => { try { return JSON.parse(readFileSync(join(catalog, 'index.json'), 'utf8')).version ?? null; } catch { return null; } })();
  // the short forms of k.time (core.word text=Mon means=Monday of=k.time.weekday.name)
  const words = [];
  for (const f of ['calendar', 'clock-words', 'clock']) {
    const p = join(catalog, `k.time/shards/${f}.sop`);
    if (existsSync(p)) words.push(...parse(readFileSync(p, 'utf8')).wires.filter((w) => w.type === 'core.word'));
  }
  const lex = [`# GENERATED by scripts/build-time-world.mjs from the catalog world w.lang.en (shard time-frames, its lexicons derived from k.time) and the short forms of k.time${commit ? ` (catalog index ${commit})` : ''}. Never edited by hand.\n`];
  for (const n of LEXICONS) {
    const w = wires.find((x) => x.type === 'w.lang.en.lex' && str(x, 'name')[0] === `time.${n}`);
    if (!w) continue;
    const items = [...new Set(str(w, 'item').map(us))];
    const forms = SHORT[n] ? words.filter((x) => str(x, 'of')[0] === SHORT[n]).flatMap((x) => str(x, 'text').map((t) => [us(str(x, 'means')[0]), us(t)])).filter(([lemma, t]) => items.includes(lemma) && !items.includes(t)) : [];
    lex.push(`@${lexId(n)} core.lexicon\n    class=noun\n    doc=${q(`${str(w, 'doc')[0] ?? n} (plural= lines are the short forms of k.time: the lemma is the full name)`)}\n${forms.map(([l, t]) => `    plural=${l}:${t}\n`).join('')}${items.map((i) => `    word=${i}\n`).join('')}`);
  }
  // the units of time (k.time.duration and k.time.span names, one or two words, with their plurals): the anchor of the reader patterns ("how many hours are in a day", "which days are the weekend")
  const kt = [];
  for (const f of ['calendar', 'clock-words', 'clock']) { const p = join(catalog, `k.time/shards/${f}.sop`); if (existsSync(p)) kt.push(...parse(readFileSync(p, 'utf8')).wires); }
  const units = [...new Set(kt.filter((w) => (w.type === 'k.time.duration' || w.type === 'k.time.span') && !str(w, 'within').length).map((w) => us(str(w, 'name')[0])).filter((n) => n.split('_').length <= 2))].sort();
  const cyclePlurals = [];
  // the cycles of k.time with a plural name ("seasons") are said in the singular too
  for (const w of kt.filter((x) => x.type === 'k.time.cycle')) { const c = us(str(w, 'name')[0]); if (/^[a-z]+s$/.test(c) && !units.includes(c.slice(0, -1))) { units.push(c.slice(0, -1)); cyclePlurals.push([c.slice(0, -1), c]); } }
  units.sort();
  const unitForms = words.filter((x) => ['k.time.duration.name', 'k.time.span.name'].includes(str(x, 'of')[0])).flatMap((x) => str(x, 'text').map((t) => [us(str(x, 'means')[0]), us(t)])).filter(([l, t]) => units.includes(l) && !units.includes(t));
  unitForms.push(...cyclePlurals);
  for (const u of [...units]) if (units.includes(`${u}s`)) { unitForms.push([u, `${u}s`]); units.splice(units.indexOf(`${u}s`), 1); }
  lex.push(`@${lexId('unit')} core.lexicon\n    class=noun\n    doc=${q('The units and spans of time: the names of k.time.duration and k.time.span of one or two words (plural= lines are the plurals k.time gives).')}\n${unitForms.map(([l, t]) => `    plural=${l}:${t}\n`).join('')}${units.map((i) => `    word=${i}\n`).join('')}`);
  const frames = [...lang.frames('acts.state'), ...lang.frames('acts')].filter((f) => f.id === 'today' || f.id.startsWith('date.') || ['month', 'season'].includes(f.id) || f.id.startsWith('clock') || f.id.startsWith('ask.'));
  const pats = [];
  for (const f of frames) {
    const act = f.act === 'ask' ? 'time.ask' : 'time.set';
    const emit = `@{_} core.request action=${act}${Object.entries(f.lit ?? {}).map(([k, v]) => ` arg.${k}=\\"${v}\\"`).join('')}${f.args.map((a) => ` arg.${a}=\\"{${a}}\\"`).join('')} arg.text=\\"{segment}\\"`;
    pats.push(`@pat.${NS}.${f.act === 'ask' ? '' : 'state.'}${f.id} core.pattern\n    match=${q(expand(f.match))}\n    emit="${emit}"\n    kind=${f.act === 'ask' ? 'question' : 'statement'}\n    priority=${f.priority}\n    signal=true\n    example=${q(f.example)}\n${CANONICAL.has(f.id) ? `    canonical=${q(f.example)}\n` : ''}`);
  }
  return { lexicon: lex.join('\n'), generated: pats.join('\n'), frames: frames.length };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  let catalog = process.argv.slice(2).find((a) => !a.startsWith('--'));
  if (!catalog) catalog = (await import('./lib/catalog-pin.mjs')).pinnedCatalog().dir;
  if (!existsSync(join(catalog, 'w.lang.en/shards/time-frames.sop'))) { console.error('usage: node scripts/build-time-world.mjs [<catalog docs/worlds dir with w.lang.en/shards/time-frames.sop>] [--check]'); process.exit(2); }
  const out = build(catalog);
  const patFile = join(DIR, 'patterns.sop'), lexFile = join(DIR, 'lexicon.sop');
  const cur = existsSync(patFile) ? readFileSync(patFile, 'utf8') : '';
  const hand = cur.includes(MARKER) ? cur.slice(0, cur.indexOf(MARKER)) : cur;
  const want = { [patFile]: `${hand.replace(/\n*$/, '\n\n')}${MARKER}\n\n${out.generated}`, [lexFile]: out.lexicon };
  let stale = 0;
  for (const [file, text] of Object.entries(want)) {
    if ((existsSync(file) ? readFileSync(file, 'utf8') : null) === text) continue;
    if (process.argv.includes('--check')) { stale++; console.error(`stale: ${file}`); } else { writeFileSync(file, text); console.log(`written ${file}`); }
  }
  console.log(`${out.frames} frames`);
  if (stale) process.exit(1);
}
