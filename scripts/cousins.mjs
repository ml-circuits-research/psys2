/**
 * COUSINS of a case, run through the real pipeline (spec 16, "Cousins of a case"; reviewer 21:55, owner 15:03). Measurement only.
 *
 *   node scripts/cousins.mjs --case <ledger id | sentence> [--degree 1..3] [--lib <sopworld checkout>] [--reasoner ops|matrix|both]
 *        [--tab talk] [--facts k.animals,k.food|all] [--catalog <dir>] [--limit N] [--label x] [--out file.json] [--show]
 *   node scripts/cousins.mjs --batch build=plans-ledger | class=paraphrase: | file=<jsonl of {text,tab}>  [--limit N] ...
 *
 * The cases are the library's: `cousins(world, { text, frame }, { degree })` (the vendored library when it exports it, else `--lib`, which is read for measurement and never imported by src/).
 * The typed world the library reads is built from the knowledge catalog (`--catalog`, default tests/fixtures/catalog; `--facts` picks the worlds): the same facts the Talk tab is given.
 * No hand-written cousin lists. Every generated case is sent to a fresh session with the tab open, under each reasoner, and judged by state and reply against the answer the library
 * computed from the world (`judge`). A sentence the types do not read gives no cousins; it is a row "no typed frame" (a class the library cannot expand yet), never a guess.
 * Table: degree x dimension (filler kind, aspect; act family, alternation and world structure are not generated by the library yet and are listed as such).
 */
import { readFileSync, writeFileSync, existsSync, readdirSync, mkdirSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { applyReasonerFlag } from './lib/reasoner-flag.mjs';
import { resolveLibrary, expand, expectedOf, judge, tabulate, tableText, DIMENSIONS } from './lib/cousins-host.mjs';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const arg = (k, d) => { const i = process.argv.indexOf(`--${k}`); return i > 0 && !process.argv[i + 1]?.startsWith('--') ? process.argv[i + 1] : d; };
const flag = (k) => process.argv.includes(`--${k}`);
const jsonl = (f) => (existsSync(f) ? readFileSync(f, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l)) : []);

/** The cases to expand: a ledger id (training/eval/cases.jsonl, latest observation), a sentence, or a batch of the ledger. */
export function casesFromArgs() {
  const limit = Number(arg('limit', 0)) || Infinity;
  const one = arg('case', null), batch = arg('batch', null);
  if (one) {
    const rows = jsonl(join(REPO, 'training/eval/cases.jsonl')).filter((r) => r.id === one || r.id?.startsWith(one));
    const r = rows.at(-1);
    return [r ? { id: r.id, text: r.text, tab: r.tab } : { id: null, text: one, tab: null }];
  }
  if (!batch) throw new Error('usage: --case <ledger id | sentence> or --batch build=<b> | class=<prefix> | file=<jsonl>');
  const [k, v] = [batch.slice(0, batch.indexOf('=')), batch.slice(batch.indexOf('=') + 1)];
  let rows;
  if (k === 'file') rows = jsonl(resolve(v));
  else rows = jsonl(join(REPO, 'training/eval/failures.jsonl')).filter((r) => (k === 'build' ? r.build === v : String(r.class ?? '').startsWith(v)));
  const seen = new Set();
  return rows.filter((r) => !seen.has(r.text) && seen.add(r.text)).slice(0, limit).map((r) => ({ id: r.id ?? null, text: r.text, tab: r.tab }));
}

/** The typed world the library reads: schemas and shards of the catalog worlds as wires of one library World. */
export function buildWorld(lib, { catalog, facts }) {
  const dirs = facts === 'all' ? readdirSync(catalog).filter((d) => existsSync(join(catalog, d, 'schema.sop'))) : facts.split(',');
  const w = new lib.World(), skipped = [];
  for (const d of dirs) {
    const base = join(catalog, d);
    const parts = [existsSync(join(base, 'schema.sop')) ? readFileSync(join(base, 'schema.sop'), 'utf8') : ''];
    const sh = join(base, 'shards');
    if (existsSync(sh)) for (const f of readdirSync(sh).sort()) if (f.endsWith('.sop')) parts.push(readFileSync(join(sh, f), 'utf8'));
    for (const t of parts) { try { w.tell(t); } catch { skipped.push(d); } }   // a text the library refuses (a duplicate id across worlds) is left out and listed
  }
  w.skipped = [...new Set(skipped)];
  return w;
}

async function runPipeline({ catalog, tab, texts }) {
  const { createFsLoader, DEFAULT_ROOT } = await import('../src/loaders/fs-loader.mjs');
  const { createEngine } = await import('../src/dialog/index.mjs');
  const { sessionOptions, settingsForMode } = await import('../src/dialog/runtime-config.mjs');
  const { createFacts } = await import('../src/knowledge/facts.mjs');
  const { visibleState: vs } = await import('./lib/visible-state.mjs');
  // a question changes no world; the Talk tab's own record (cards), the mentioned things (session.things) and the shell are the view of the question, not a change of a world
  const visibleState = (st) => Object.fromEntries(Object.entries(vs(st)).filter(([k, v]) => !['talk', 'ui.shell', 'session.things'].includes(k) && JSON.stringify(v) !== '{}'));
  const source = { text: async (p) => { try { return readFileSync(`${catalog}/${p}`, 'utf8'); } catch { return null; } } };
  const engine = await createEngine({ loader: createFsLoader({ roots: [DEFAULT_ROOT] }) });
  const out = new Map();
  for (const t of texts) {
    engine.setKnowledge(createFacts({ source }));
    const s = engine.createSession(sessionOptions(settingsForMode('rules'), { language: 'en' }));
    s.setWorldState('ui.shell', { activeTab: tab });
    const before = visibleState(s.state());
    let reply = '';
    try { reply = (await s.send(t)).text ?? ''; } catch (e) { reply = ''; }
    out.set(t, { reply, before, after: visibleState(s.state()) });
  }
  return { reasoner: engine.reasonerMode, runs: out };
}

/** One reasoner: the generated cases of every case, each run once, judged. Rows carry the case, degree, dimension and outcome. */
async function measure() {
  const reasoner = applyReasonerFlag();
  const degree = Number(arg('degree', 2));
  const catalog = resolve(arg('catalog', join(REPO, 'tests/fixtures/catalog')));
  const tab = arg('tab', 'talk');
  let vendored = null;
  try { vendored = await import('../src/vendor/sopworld/sopworld.mjs'); } catch { /* no vendored library */ }
  const { lib, source } = await resolveLibrary({ vendored, libPath: arg('lib', null) });
  const world = buildWorld(lib, { catalog, facts: arg('facts', 'k.animals') });
  const cases = casesFromArgs();
  const rows = [], noFrame = [], texts = [], perCase = [];
  const plan = cases.map((c) => {
    const r = expand(lib, world, { text: c.text }, { degree, n: Number(arg('n', 50)) });
    perCase.push({ text: c.text, frame: r.frame ? { is: r.frame.is, key: r.frame.key ?? r.frame.act ?? null, of: r.frame.of ?? null } : null, generated: (r.cousins ?? []).length, valid: (r.cousins ?? []).filter((x) => x.valid).length });
    if (!r.frame) { noFrame.push({ id: c.id, text: c.text, why: r.why }); return { c, r }; }
    for (const x of r.cousins.filter((x) => x.valid && x.text)) texts.push(x.text);
    return { c, r };
  });
  const piped = texts.length ? await runPipeline({ catalog, tab: cases[0].tab && cases[0].tab !== 'null' ? cases[0].tab : tab, texts: [...new Set(texts)] }) : { runs: new Map() };
  for (const { c, r } of plan) {
    for (const x of (r.cousins ?? []).filter((x) => x.valid && x.text)) {
      const run = piped.runs.get(x.text);
      const j = judge(x, expectedOf(world, x), run);
      rows.push({ case: c.text, caseId: c.id, text: x.text, degree: x.degree, dimension: x.dimension, outcome: j.outcome, why: j.why, reply: run.reply.slice(0, 160), key: x.frame.key, answer: x.frame.answer });
    }
  }
  return { reasoner, library: source, degree, facts: arg('facts', 'k.animals'), cases: cases.length, perCase, skippedWorlds: world.skipped, noFrame, rows };
}

function report(res) {
  const lines = [`reasoner ${res.reasoner}; library ${res.library}; facts ${res.facts}; ${res.cases} case(s), ${res.noFrame.length} with no typed frame, ${res.rows.length} generated cousins run`];
  const by = {};
  for (const c of res.perCase ?? []) { const k = c.frame ? c.frame.is : 'none'; const e = by[k] ??= { cases: 0, valid: 0 }; e.cases++; e.valid += c.valid; }
  lines.push(`frames read: ${Object.entries(by).map(([k, e]) => `${k} ${e.cases} case(s) -> ${e.valid} valid cousins`).join('; ') || 'none'}`);
  if (res.skippedWorlds?.length) lines.push(`catalog worlds the library refused to load: ${res.skippedWorlds.join(', ')}`);
  lines.push(tableText(tabulate(res.rows), { title: 'degree x dimension' }));
  for (const [k, v] of Object.entries(DIMENSIONS)) if (!['filler', 'key'].includes(k)) lines.push(`  ${v}: not generated by the library (0.73 has filler and key only)`);
  const noFrameTxt = res.noFrame.slice(0, 8).map((x) => `  - ${x.text}`);
  if (noFrameTxt.length) lines.push(`no typed frame (${res.noFrame.length}):`, ...noFrameTxt);
  if (flag('show')) for (const r of res.rows.filter((x) => x.outcome !== 'right').slice(0, 30)) lines.push(`  [${r.degree} ${r.dimension}] ${r.text} -> ${r.outcome} (${r.why}) ${JSON.stringify(r.reply)}`);
  return lines.join('\n');
}

/** The "cousins of real cases" set for the learning curve (off until the vendored library has cousins): the share right of the valid cousins of the real cases, matrix reasoner. */
function recordReal(res) {
  if (res.library !== 'vendored') { console.log(`--record-real skipped: the cousins came from ${res.library}, not the vendored library (the curve only takes a vendored measure)`); return; }
  const right = res.rows.filter((r) => r.outcome === 'right').length;
  writeFileSync(join(REPO, 'training/eval/cousins-real.json'), JSON.stringify({ date: new Date().toISOString().slice(0, 10), degree: res.degree, right, total: res.rows.length, cases: res.cases }, null, 1));
  console.log(`cousins-real.json: ${right} / ${res.rows.length}`);
}

async function main() {
  const which = arg('reasoner', 'both');
  if (which === 'both') {
    const results = [];
    for (const r of ['ops', 'matrix']) {
      const tmp = join(process.env.TMPDIR ?? '/tmp', `cousins-${process.pid}-${r}.json`);
      const child = spawnSync(process.execPath, [fileURLToPath(import.meta.url), ...process.argv.slice(2).filter((a, i, v) => a !== '--reasoner' && v[i - 1] !== '--reasoner'), '--reasoner', r, '--out', tmp, '--quiet'], { encoding: 'utf8', stdio: ['ignore', 'inherit', 'inherit'] });
      if (child.status !== 0 || !existsSync(tmp)) throw new Error(`the ${r} run failed`);
      results.push(JSON.parse(readFileSync(tmp, 'utf8')));
    }
    for (const r of results) console.log(`${report(r)}\n`);
    const all = { both: true, runs: results };
    if (flag('record-real')) recordReal(results.find((r) => r.reasoner === 'matrix'));
    if (arg('out', null)) writeFileSync(arg('out'), JSON.stringify(all, null, 1));
    else { const d = join(REPO, 'training/results/cousins'); mkdirSync(d, { recursive: true }); writeFileSync(join(d, `${new Date().toISOString().slice(0, 10)}-${arg('label', 'run')}.json`), JSON.stringify(all, null, 1)); }
    return;
  }
  const res = await measure();
  if (arg('out', null)) writeFileSync(arg('out'), JSON.stringify(res));
  if (!flag('quiet')) console.log(report(res));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) await main();
