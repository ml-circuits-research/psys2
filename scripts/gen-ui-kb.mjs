// Builds the knowledge bases (kb.sop) of the three UI worlds from what the loaded worlds declare (spec 15, "ui.avatar, ui.shell and ui.help on the matrix").
//
//   node scripts/gen-ui-kb.mjs            writes worlds/ui.shell/kb.sop, worlds/ui.help/kb.sop and worlds/ui.avatar/kb.sop
//   node scripts/gen-ui-kb.mjs --check    exits 1 when a file on disk differs from what would be generated (tests/reasoner-ui.test.mjs does the same)
//
//   ui.shell   the tabs (the builtin ones of ops.mjs and the ones other worlds declare in their manifests: tab, tabTitle, tabAlias, tabNew, tabHint, tabGiveUp),
//              the words that name each tab, the game actions of a tab, the languages, the tabs of the Settings dialog
//   ui.help    what each world can do: its tab, its summary and its canonical examples, from the manifests and the patterns
//   ui.avatar  the characters, which components and colors each has, which spoken parts name which color, the color names, the optional components
// A kb.sop is data: nothing in it is written by hand. Run this script again after a world's manifest, patterns or the avatar tables change.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createFsLoader, DEFAULT_ROOT } from '../src/loaders/fs-loader.mjs';
import { loadWorlds } from '../src/worlds/index.mjs';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const files = {};   // what a generator leaves for the others (the words of the help lexicon)
const NOTE = (what) => `@gen.kb core.note text="Generated by scripts/gen-ui-kb.mjs from ${what}. Do not edit by hand: run node scripts/gen-ui-kb.mjs"`;
const atom = (x) => String(x).replace(/[^\w.-]/g, '_');   // a word as the wires write it (spaces and punctuation become underscores)
const idPart = (x) => String(x).replace(/[^\w-]/g, '_');   // a part of a wire id
const str = (x) => JSON.stringify(String(x));
const source = (text, id) => text.split('\n').map((l) => (l.startsWith('@') ? `${l} core.source="generated:scripts/gen-ui-kb.mjs:${id}"` : l)).join('\n');   // a kb wire says where it comes from

export async function buildAll({ root = DEFAULT_ROOT } = {}) {
  const loader = createFsLoader({ roots: [root] });
  const set = await loadWorlds(loader, { reasoner: 'ops' });
  const worlds = set.list();
  return {
    'ui.shell': source(await shellKb(set, worlds), 'ui.shell'),
    'ui.help': source(await helpKb(set, worlds), 'ui.help'),
    'ui.avatar': source(await avatarKb(set, worlds), 'ui.avatar'),
  };
}

// ---- ui.shell ---------------------------------------------------------------------------------------------------------------------------------------------
async function shellKb(set, worlds) {
  const ops = await import('../worlds/ui.shell/ops.mjs');
  ops.refresh({ worlds: () => worlds.map((w) => ({ id: w.id, title: w.title, summary: w.summaryPhrase, status: w.status, doc: w.doc, tab: w.tab })) });
  const out = [NOTE('worlds/ui.shell/ops.mjs (the builtin tabs and words) and the tab manifests of every world'), ''];
    for (const [id, t] of Object.entries(ops.TABS)) out.push(`@kb.shell.tab.${idPart(id)} ui.shell.known id=${atom(id)} title=${str(t.title)} world=${t.world}`);
  out.push('');
  const seen = new Set();
  for (const [w, id] of Object.entries(ops.TAB_OF_WORD)) {
    const a = atom(w);
    if (seen.has(a)) continue;
    seen.add(a);
    out.push(`@kb.shell.alias.${idPart(a)} ui.shell.alias word=${a} tab=${atom(id)}`);
  }
  for (const id of Object.keys(ops.TABS)) {
    const a = atom(id);
    if (seen.has(a)) continue;
    seen.add(a);
    out.push(`@kb.shell.alias.${idPart(a)} ui.shell.alias word=${a} tab=${a}`);
  }
  out.push('');
  const games = new Set([...Object.keys(ops.GAME_ACTIONS.new), ...Object.keys(ops.GAME_ACTIONS.hint), ...Object.keys(ops.GAME_ACTIONS.giveUp)]);
  for (const id of [...games].sort()) {
    const g = ops.GAME_ACTIONS;
    out.push(`@kb.shell.game.${idPart(id)} ui.shell.game tab=${atom(id)}${g.new[id] ? ` new=${g.new[id]}` : ''}${g.hint[id] ? ` hint=${g.hint[id]}` : ''}${g.giveUp[id] ? ` giveup=${g.giveUp[id]}` : ''}`);
  }
  out.push('');
  for (const [w, code] of Object.entries(ops.LANG_OF)) out.push(`@kb.shell.lang.${idPart(w)} ui.shell.lang word=${atom(w)} code=${code}`);
  out.push('');
  const titles = Object.values(ops.SETTINGS_TITLES);
  out.push(`@kb.shell.settings ui.shell.settings tabs=${str(`${titles.slice(0, -1).join(', ')} and ${titles.at(-1)}`)}`);
  for (const [id, t] of Object.entries(ops.SETTINGS_TITLES)) out.push(`@kb.shell.stab.${idPart(id)} ui.shell.stab id=${atom(id)} title=${str(t)}`);
  const sseen = new Set();
  for (const [w, id] of Object.entries(ops.SETTINGS_TABS)) { const a = atom(w); if (!sseen.has(a)) { sseen.add(a); out.push(`@kb.shell.salias.${idPart(a)} ui.shell.salias word=${a} tab=${atom(id)}`); } }
  return `${out.join('\n')}\n`;
}

// ---- ui.help ----------------------------------------------------------------------------------------------------------------------------------------------
async function helpKb(set, worlds) {
  const ops = await import('../worlds/ui.help/ops.mjs');
  const shell = await import('../worlds/ui.shell/ops.mjs');
  const out = [NOTE('the manifests (summary, tab) and the canonical examples of the patterns of every world'), ''];
  const ctx = { patterns: (id) => (set.get(id)?.patterns ?? []).map((p) => ({ id: p.id, kind: p.kind, priority: p.priority, examples: [...p.examples], canonical: [...(p.canonical ?? [])] })) };
  shell.refresh({ worlds: () => worlds.map((w) => ({ id: w.id, title: w.title, summary: w.summaryPhrase, status: w.status, doc: w.doc, tab: w.tab })) });
  const says = new Map();   // world id -> the sentence
  for (const w of worlds) {
    const summary = String(w.summaryPhrase ?? '').trim();
    if (!summary || w.id === 'ui.help' || w.id === 'core') continue;
    const items = ops.exampleList(ctx, w.id).slice(0, 3);
    if (items.length) says.set(w.id, `To ${summary}, you can say, for example: ${ops.joinOr(items.map(ops.quote))}.`);
  }
  // the words that name an area, in the order that settles a clash: the words of the tabs (the shell's own table), the last part of a world's name, the last word of its summary
  const ofWord = new Map();
  const add = (word, id) => { const a = atom(word); if (a && says.has(id) && !ofWord.has(a)) ofWord.set(a, id); };
  for (const [word, tab] of Object.entries(shell.TAB_OF_WORD)) add(word, shell.TABS[tab]?.world);
  for (const w of worlds) { for (const a of [w.tab?.id, w.tab?.title, ...(w.tab?.aliases ?? [])]) if (a) add(shell.norm(a), w.id); }
  for (const w of worlds) { const last = w.id.split('.').pop(); if (last !== 'common') add(last, w.id); }
  for (const w of worlds) { const ws = String(w.summaryPhrase ?? '').trim().split(/\s+/); const last = ws.at(-1).toLowerCase(); if (last.length >= 4 || ws.length === 1) add(last, w.id); }
  const areas = [...ofWord.keys()].sort();
  for (const a of areas) out.push(`@kb.help.area.${idPart(a)} ui.help.area word=${a} world=${ofWord.get(a)} says=${str(says.get(ofWord.get(a)))}`);
  files.helpWords = areas.sort();
  return `${out.join('\n')}\n`;
}
// ---- ui.avatar --------------------------------------------------------------------------------------------------------------------------------------------
async function avatarKb(set) {
  const ops = await import('../worlds/ui.avatar/ops.mjs');
  const lex = (id) => { const l = set.list().flatMap((w) => w.lexicons).find((x) => x.id === id); return l ? [...l.words] : []; };
  const tok = (v) => (/^[\w.-]+$/.test(String(v)) ? String(v) : str(v));
  const cap = (x) => x.replace(/^./, (c) => c.toUpperCase());
  const plural = (x) => (/s$/.test(x) ? x : `${x}s`);
  const joinAnd = (a) => (a.length <= 1 ? a.join('') : `${a.slice(0, -1).join(', ')} and ${a.at(-1)}`);
  const out = [NOTE('worlds/ui.avatar/lexicon.sop (the DiceBear data lexicons) and the tables of worlds/ui.avatar/ops.mjs'), ''];
  for (const ch of ops.CHARACTERS) {
    const spoken = ops.SPOKEN_CHARACTER[ch];
    out.push(`@kb.av.char.${ch} ui.avatar.char id=${ch} spoken=${str(spoken)} cap=${str(cap(spoken))}`);
  }
  const comps = {};
  for (const ch of ops.CHARACTERS) comps[ch] = lex(`${ops.DATA}${ch}.components`);
  for (const ch of ops.CHARACTERS) for (const key of comps[ch]) {
    const optional = new Set(lex(`${ops.DATA}${ch}.optional`));
    const seen = new Set(), shown = [];
    for (const w of lex(`${ops.DATA}${ch}.${key}`)) {
      const [, id, display] = w.split(':');
      if (seen.has(id)) continue;
      seen.add(id);
      const d = (display ?? id).replace(/_/g, ' ');
      shown.push(d);
    }
    const names = [...new Set(shown)];
    const list = names.length > 10 ? `${names.slice(0, 10).join(', ')} and ${names.length - 10} more` : joinAnd(names);
    out.push(`@kb.av.slot.${ch}.${idPart(key)} ui.avatar.slot ch=${ch} key=${atom(key)} optional=${optional.has(key)} nouns=${str(cap(plural(ops.LABEL[key] ?? key)))} list=${str(list)}`);
  }
  const init = ops.initialState();
  for (const ch of ops.CHARACTERS) if (!init[ch]) out.push(`@kb.av.start.${ch} ui.avatar.start ch=${ch} look=${str(JSON.stringify(ops.defaultLook({ lexicon: lex }, ch)))}`);
  for (const [part, map] of Object.entries(ops.COLOR_KEYS)) {
    out.push(`@kb.av.partname.${idPart(part)} ui.avatar.partname word=${atom(part)} core=${ops.CORE.some((c) => map[c])}`);
    for (const ch of ops.CHARACTERS) if (map[ch]) out.push(`@kb.av.paint.${idPart(part)}.${ch} ui.avatar.paint part=${atom(part)} ch=${ch} key=${atom(map[ch])}`);
  }
  for (const w of lex('lex.ui.avatar.data.colornames')) { const [name, hex] = w.split(':'); out.push(`@kb.av.cname.${idPart(name)} ui.avatar.colorname name=${atom(name)} hex=${tok(hex)}`); }
  return `${out.join('\n')}\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const files = await buildAll();
  const check = process.argv.includes('--check');
  let bad = 0;
  for (const [id, text] of Object.entries(files)) {
    if (!text) continue;
    const file = join(REPO, 'worlds', id, 'kb.sop');
    if (check) { if (!existsSync(file) || readFileSync(file, 'utf8') !== text) { console.error(`${file} is out of date`); bad++; } }
    else writeFileSync(file, text);
  }
  if (check && bad) process.exit(1);
  if (!check) console.log('kb.sop written');
}
