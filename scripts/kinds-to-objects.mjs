/**
 * Describes the built-in kinds of the drawing board (worlds/art.draw/scene.mjs) as `k.objects` facts (spec 07, DRAW-FROM-FACTS): one object per kind, parts with a primitive
 * shape, a box in the 0-100 frame, a draw order, colours, points as separate wires. Written to knowledge/art.draw.kinds/shards/kinds.sop.
 *   node scripts/kinds-to-objects.mjs [--check]
 * What the facts cannot say (so a picture from facts differs from the hand-coded one): the thickness of a line, a merged silhouette (`mg`), a lightness shift (`sh`), the
 * fill override of one part (`f`), a part that follows the colour of the object (only the main part does), the smile of a mood. The report lists them per kind.
 */
import { writeFileSync, readFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { KIND_ORDER, colorHex, canonColor, handCodedParts } from '../worlds/art.draw/scene.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'knowledge/art.draw.kinds/shards/kinds.sop');
const r1 = (v) => Math.round(v * 100) / 100;
const BASE = ['black', 'white', 'grey', 'red', 'orange', 'yellow', 'green', 'blue', 'purple', 'pink', 'brown'];

const ptsOf = (p) => {
  if (p.s === 'poly' || p.s === 'line') return p.pts;
  if (p.s === 'curve') {   // a smooth curve through its points, as a polyline
    const out = [], q = p.pts;
    for (let i = 0; i < q.length - 1; i++) {
      const a = q[Math.max(0, i - 1)], b = q[i], c = q[i + 1], d = q[Math.min(q.length - 1, i + 2)];
      for (let t = 0; t < 1; t += 0.25) out.push([0.5 * (2 * b[0] + (-a[0] + c[0]) * t + (2 * a[0] - 5 * b[0] + 4 * c[0] - d[0]) * t * t + (-a[0] + 3 * b[0] - 3 * c[0] + d[0]) * t ** 3), 0.5 * (2 * b[1] + (-a[1] + c[1]) * t + (2 * a[1] - 5 * b[1] + 4 * c[1] - d[1]) * t * t + (-a[1] + 3 * b[1] - 3 * c[1] + d[1]) * t ** 3)]);
    }
    out.push(q.at(-1));
    return out;
  }
  if (p.s === 'ellipse' && p.r) {   // a turned ellipse is a polygon
    const a = (p.r * Math.PI) / 180, out = [];
    for (let i = 0; i < 24; i++) { const t = (i / 24) * Math.PI * 2, x = (Math.cos(t) * p.w) / 2, y = (Math.sin(t) * p.h) / 2; out.push([p.x + x * Math.cos(a) - y * Math.sin(a), p.y + x * Math.sin(a) + y * Math.cos(a)]); }
    return out;
  }
  return null;
};
const boxOf = (p) => {
  const pts = ptsOf(p);
  if (pts) { const xs = pts.map((q) => q[0]), ys = pts.map((q) => q[1]); return [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)]; }
  if (p.s === 'arc') return [p.x - p.w / 2, p.y - p.h / 2, p.x + p.w / 2, p.y];
  return [p.x - p.w / 2, p.y - p.h / 2, p.x + p.w / 2, p.y + p.h / 2];
};

export function describeKind(kind) {
  const parts = handCodedParts(kind);
  const boxes = parts.map(boxOf);
  const x0 = Math.min(...boxes.map((b) => b[0])), x1 = Math.max(...boxes.map((b) => b[2])), y0 = Math.min(...boxes.map((b) => b[1])), y1 = Math.max(...boxes.map((b) => b[3]));
  const cw = x1 - x0, ch = y1 - y0, k = 100 / Math.max(cw, ch), ox = (100 - cw * k) / 2, oy = (100 - ch * k) / 2;
  const X = (v) => r1((v - x0) * k + ox), Y = (v) => r1((v - y0) * k + oy);
  const lossy = new Set();
  const seen = {}, wires = [];
  parts.forEach((p, i) => {
    const n = (seen[p.n] = (seen[p.n] ?? 0) + 1), name = n === 1 ? p.n : `${p.n}_${n}`;
    if (p.mg) lossy.add('merged silhouette'); if (p.sh) lossy.add('lightness shift'); if (p.f) lossy.add('fill override'); if (p.s === 'curve') lossy.add('curve as polyline');
    if (p.t && (p.s === 'line' || p.s === 'curve' || p.s === 'arc') && p.t !== 0.02) lossy.add('line thickness');
    if (p.m && i !== 0) lossy.add('follows object colour');
    const pts = ptsOf(p), b = boxOf(p);
    const a = { of: kind, name, kind: p.n, z: i, colour: BASE.includes((canonColor(p.c) ?? '').split(' ').at(-1)) ? (canonColor(p.c) ?? '').split(' ').at(-1) : 'grey' };
    a.rgb = `"${colorHex(p.c)}"`;
    const bx = X(b[0]), by = Y(b[1]), bw = r1(X(b[2]) - bx), bh = r1(Y(b[3]) - by);
    let shape;
    if (p.s === 'rect') shape = Math.abs(p.w - p.h) < 1e-6 ? 'square' : 'rectangle';
    else if (p.s === 'ellipse' && !p.r) shape = Math.abs(p.w - p.h) < 1e-6 ? 'circle' : 'oval';
    else if (p.s === 'poly' || (p.s === 'ellipse' && p.r)) shape = 'polygon';
    else if (p.s === 'line' || p.s === 'curve') shape = 'line';
    else if (p.s === 'arc') { shape = 'arc'; a.opens = 'down'; }
    wires.push({ a: { ...a, shape, x: bx, y: by, w: bw, h: bh }, pts: shape === 'polygon' || shape === 'line' ? pts.map(([x, y]) => [X(x), Y(y)]) : null, name });
  });
  return { kind, lossy: [...lossy], wires };
}

export function build() {
  const lines = ['# art.draw.kinds: the built-in kinds of the drawing board described as k.objects facts (generated by scripts/kinds-to-objects.mjs; do not edit).', '# status=fixture. Same format as sop-knowledge-worlds k.objects: parts with a primitive shape, a box x y w h in the 0-100 frame, z, colour (rgb exact), points as separate wires.', ''];
  const report = [];
  for (const kind of KIND_ORDER) {
    const d = describeKind(kind);
    report.push(d);
    lines.push(`# ${kind}`, `@k.objects.kind_${kind} k.objects.object name=${kind}`);
    for (const { a, pts, name } of d.wires) {
      lines.push(`@k.objects.kind_${kind}.${name} k.objects.part of=${kind} name=${name} kind=${a.kind} shape=${a.shape} x=${a.x} y=${a.y} w=${a.w} h=${a.h} z=${a.z} colour=${a.colour} rgb=${a.rgb}${a.opens ? ` opens=${a.opens}` : ''}`);
      (pts ?? []).forEach(([x, y], i) => lines.push(`@k.objects.kind_${kind}.${name}.p${i + 1} k.objects.point part=$k.objects.kind_${kind}.${name} n=${i + 1} x=${x} y=${y}`));
    }
    lines.push('');
  }
  return { text: `${lines.join('\n')}\n`, report };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { text, report } = build();
  if (process.argv.includes('--check')) {
    const same = existsSync(OUT) && readFileSync(OUT, 'utf8') === text;
    console.log(same ? 'kinds.sop is up to date' : 'kinds.sop is STALE: run node scripts/kinds-to-objects.mjs');
    process.exit(same ? 0 : 1);
  }
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, text);
  for (const d of report) console.log(`${d.kind.padEnd(10)} ${d.wires.length} parts  ${d.lossy.join(', ')}`);
}
