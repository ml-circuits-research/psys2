  const out = await generate();
  const check = process.argv.includes('--check');
  let stale = false;
  for (const f of ['legend.sop', 'lexicon.sop']) {
    const p = path.join(WORLD, f);
    if (check) { const cur = await readFile(p, 'utf8').catch(() => ''); if (cur !== out[f]) { stale = true; console.error(`${f} is out of date`); } } else await writeFile(p, out[f]);
  }
  if (check) process.exit(stale ? 1 : 0);
  console.log(`ui.avatar: generated legend.sop and lexicon.sop (DiceBear core ${out.summary.core}, styles ${out.summary.styles}; ${out.summary.options} option words, ${out.summary.synonyms} synonyms)`);
