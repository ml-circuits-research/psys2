// Builds the legend and the base lexicon of the world `ui.avatar` from the DiceBear style definitions.
//
// This is a small, runnable example of the C1 workflow (vision: C1 builds a legend from a tool's own documentation):
// the tool here is the DiceBear library, its "documentation" is the machine-readable style definitions
// (docs/webchat/vendor/dicebear-styles/*.json). Their components, variants and colour palettes BECOME the world's
// legend (types, keys, `ask` questions) and its lexicon (the words people can say). Everything generated is
// marked with a `core.note` header wire (its `text` carries the "Generated by ... do not edit by hand" notice; core.note has no `doc` key); the hand-written language layer lives in patterns.sop and lexicon.extra.sop.
//
//   node scripts/legend-from-dicebear.mjs            writes worlds/ui.avatar/legend.sop and worlds/ui.avatar/lexicon.sop
//   node scripts/legend-from-dicebear.mjs --check    exits 1 when the files on disk differ from what would be generated
//
// Output (deterministic):
//   legend.sop   type ui.avatar.character (active, name, seed) and one type per character style
//                (robot = voxel-bot, person = open-peeps, emoji = moods), one key per component (value = variant atom,
//                `doc` lists the variants) and one key per colour, named like DiceBear's `<color>Color` options (value = a 6-digit hex entry of the style palette).
//   lexicon.sop  generated lexicons + the verbatim content of lexicon.extra.sop (the world loader reads only lexicon.sop).
//     lex.ui.avatar.options             every variant, as the words people say (last word singular), plus synonyms
//     lex.ui.avatar.characters          robot, person, emoji (+ synonyms)
//     lex.ui.avatar.colors              colour names (red, light_blue, dark_green ...)
//     lex.ui.avatar.data.*              data for ops.mjs, which cannot import anything:
//         data.characters                 <word>:<type>
//         data.<character>.components     component keys (also .optional and .colors)
//         data.<character>.<component>    <word>:<variant id>:<display words joined by _>   (in style order)
//         data.colornames                 <name>:<hex>
//         palette.<character>.<colour>    hex entries of the style palette
//   lexicon.extra.sop may contain `syn.<component>` lexicons (word=<synonym>:<target word>) that add synonyms to
//   the generated words, `names.<component>` lexicons (word=<variant id>:<spoken name>) that give numbered or cryptic
//   variants a descriptive name (short3 -> short_curly_hair: the name replaces the display words ops.mjs speaks and
//   is itself a word people can say), and `alias.<component>` lexicons (word=<alias>:<variant id>) that add a word
//   for exactly one variant; every other wire in it is copied unchanged.
