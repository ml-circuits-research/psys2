const DERIVED = ['red', 'orange', 'yellow', 'green', 'blue', 'purple', 'pink', 'brown', 'gray', 'cyan', 'teal', 'violet', 'turquoise'];

const hexToRgb = (h) => [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
const rgbToHex = (rgb) => rgb.map((v) => Math.round(Math.max(0, Math.min(255, v))).toString(16).padStart(2, '0')).join('');
const mix = (hex, to, t) => rgbToHex(hexToRgb(hex).map((v, i) => v + (to[i] - v) * t));
export function colorNames() {
  const out = { ...BASE_COLORS };
  for (const n of DERIVED) {
    out[`light_${n}`] = mix(BASE_COLORS[n], [255, 255, 255], 0.45);
    out[`dark_${n}`] = mix(BASE_COLORS[n], [0, 0, 0], 0.4);
  }
  return out;
}

// ---- word handling ---------------------------------------------------------------------------------------------
/** angryWithFang -> ['angry','with','fang']; glasses2 -> ['glasses', '2']. */
export function splitName(id) {
  return id.replace(/([a-z])([A-Z])/g, '$1 $2').replace(/([A-Z]+)([A-Z][a-z])/g, '$1 $2').replace(/([A-Za-z])(\d)/g, '$1 $2').toLowerCase().split(' ').filter(Boolean);
}
/** The matching word of a name: digits dropped, last word singular (the rule engine matches lemmas): 'glasses2' -> 'glass'. */
export function lemmaOf(words) {
  const w = words.filter((x) => !/^\d+$/.test(x));
  if (!w.length) return '';
  w[w.length - 1] = singularLemma(w[w.length - 1], new Map());
  return w.join('_');
}
const display = (words) => words.map((w) => (/^\d+$/.test(w) ? String(Number(w)) : w)).join('_');
const snake = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '');
const lemmaOfPhrase = (s) => lemmaOf(snake(s).split('_'));
/** Lexicon words for a spoken name: hyphens kept (one token) and split (several tokens); at most 3 tokens (the matcher's limit). */
const spokenForms = (name) => {
  const kept = name.toLowerCase().split(/[_\s]+/).filter(Boolean);
  const forms = new Set([lemmaOf(kept), lemmaOfPhrase(name)]);
  return [...forms].filter((w) => w && w.split('_').length <= 3);
};

// ---- SOP output -------------------------------------------------------------------------------------------------
const ATOM = /^[^\s"@$=\\]+$/;
const REF = /^\$[A-Za-z_][\w.-]*$/;   // a reference such as $lex.lang.colour is written bare
const val = (v) => (typeof v === 'number' || typeof v === 'boolean' || ATOM.test(String(v)) || REF.test(String(v)) ? String(v) : JSON.stringify(String(v)));
const wire = (id, type, pairs) => `@${id} ${type}\n${pairs.map(([k, v]) => `    ${k}=${val(v)}`).join('\n')}\n`;
const lexicon = (id, cls, doc, words, extra = []) => wire(id, 'core.lexicon', [['class', cls], ['doc', doc], ...words.map((w) => ['word', w]), ...extra]);

async function readJson(p) { return JSON.parse(await readFile(p, 'utf8')); }

async function versions() {
  const core = (await readFile(path.join(VENDOR, 'dicebear-core.mjs'), 'utf8')).slice(0, 200).match(/@dicebear\/core ([\d.]+)/)?.[1] ?? '?';
  let styles = '?';
  for (const f of ['README.md', 'dicebear-styles/LICENSES.md']) { // the version of the style definitions is named in either
    const hit = (await readFile(path.join(VENDOR, f), 'utf8').catch(() => '')).match(/@dicebear\/styles ([\d.]+)/)?.[1];
    if (hit) { styles = hit; break; }
  }
  return { core, styles };
}

/** Read the style definitions into a plain model. */
async function loadModel() {
  const model = [];
  const peeps = await readJson(path.join(VENDOR, 'dicebear-styles', 'open-peeps.json'));
  for (const c of CHARACTERS) {
    const def = await readJson(path.join(VENDOR, 'dicebear-styles', `${c.style}.json`));
    const components = [];
    for (const [key, comp] of Object.entries(def.components)) {
      if (SKIP_COMPONENTS.has(key)) continue;
      const optional = comp.probability != null;
      if (!comp.variants || (Object.keys(comp.variants).length < 2 && !optional)) continue; // a shared piece of the drawing, not a choice
      const ids = Object.keys(comp.variants);
      const numbered = ids.every((id) => NUMBERED_ID.test(id));
      const variants = ids.map((id) => {
        if (!numbered) return { id, words: splitName(id), lemma: lemmaOf(splitName(id)) };
        const n = String(Number(id.match(/\d+/)[0]));
        return { id, words: ['style', n], lemma: NUMBERED_WORD[key] ?? 'style', numbered: true };
      });
      components.push({ key, optional, variants, numbered });
    }
    const colors = [];
    for (const [key, col] of Object.entries(def.colors)) {
      let values = col.values.map((v) => v.replace('#', '').toLowerCase());
      const borrow = BORROW_PALETTE[c.style]?.[key];
      if (values.length < 2 && borrow && peeps.colors[borrow]) values = peeps.colors[borrow].values.map((v) => v.replace('#', '').toLowerCase());
      if (values.length < 2) continue; // a fixed colour (ink) cannot be chosen
      colors.push({ key, values, notEqualTo: col.notEqualTo ?? [] });
    }
    model.push({ ...c, license: def.meta?.license?.name ?? '?', creator: def.meta?.creator?.name ?? '?', components, colors });
  }
  return model;
}

/** Synonyms and other hand-written lexicons from lexicon.extra.sop. */
async function loadExtra() {
  let text = '';
  try { text = await readFile(path.join(WORLD, 'lexicon.extra.sop'), 'utf8'); } catch { return { synonyms: [], names: [], aliases: [], verbatim: '' }; }
  const { wires, errors } = parse(text, { source: 'lexicon.extra.sop' });
  if (errors.length) throw new Error(`lexicon.extra.sop: ${errors[0].message} (line ${errors[0].line})`);
  const synonyms = [], names = [], aliases = [];
  for (const w of wires) {
    if (w.id.startsWith('names.') || w.id.startsWith('alias.')) {
      const kind = w.id.startsWith('names.') ? names : aliases;
      for (const e of w.entries.filter((x) => x.key === 'word')) {
        const [left, right] = e.value.v.split(':');
        if (!left || !right) throw new Error(`${w.id}: '${e.value.v}' must be <${kind === names ? 'variant id>:<spoken name' : 'alias>:<variant id'}>`);
        kind.push(kind === names ? { logical: w.id.split('.')[1], id: left, name: right } : { logical: w.id.split('.')[1], alias: lemmaOfPhrase(left), forms: spokenForms(left), id: right });
      }
      continue;
    }
    if (!w.id.startsWith('syn.')) continue;
    const logical = w.id.split('.')[1];
    for (const e of w.entries.filter((x) => x.key === 'word')) {
      const [alias, target] = e.value.v.split(':');
      if (!alias || !target) throw new Error(`${w.id}: synonym '${e.value.v}' must be <alias>:<target word>`);
      synonyms.push({ logical, alias: lemmaOfPhrase(alias), target });
    }
  }
  // the verbatim part: everything except the syn.* wires, cut by wire boundaries
  const blocks = text.split(/^(?=@)/m).filter((b) => b.trim() && !/^@(syn|names|alias)\./.test(b));
  return { synonyms, names, aliases, verbatim: blocks.join('').trim() + '\n' };
}

export async function generate() {
  const ver = await versions();
  const model = await loadModel();
  const { synonyms, names: nameList, aliases, verbatim } = await loadExtra();
  const note = `Generated by scripts/legend-from-dicebear.mjs from DiceBear ${ver.core} (styles ${ver.styles}); do not edit by hand`;
  const names = colorNames();

  // ---- entries of every (character, component), with synonyms ----
  const entries = new Map(); // `${char}.${comp}` -> [{word, id, display}]
  const logicalWords = new Map(); // logical component -> Set of words (for the options lexicon)
  for (const c of model) {
    for (const comp of c.components) {
      const list = comp.variants.map((v) => ({ word: v.lemma, id: v.id, display: display(v.words) }));
      if (comp.optional) list.unshift({ word: OPTIONAL_NONE, id: OPTIONAL_NONE, display: OPTIONAL_NONE });
      entries.set(`${c.id}.${comp.key}`, list);
    }
  }
  // descriptive names: replace the display words of a variant and add the name itself as a word for it
  for (const n of nameList) {
    let hit = 0;
    for (const [k, list] of entries) {
      if (k === 'characters' || k.split('.')[1] !== n.logical) continue;
      const own = list.filter((x) => x.id === n.id);
      if (!own.length) continue;
      hit++;
      for (const e of own) e.display = n.name;
      // the matcher reads at most 3 tokens per lexicon entry and keeps a hyphenated word as one token, so a name with a
      // hyphen is a word both ways (side-parted, side_parted); longer names are only spoken (aliases give shorter ways)
      for (const word of spokenForms(n.name)) {
        if (!list.some((x) => x.id === n.id && x.word === word)) list.push({ word, id: n.id, display: n.name });
      }
    }
    if (!hit) throw new Error(`names.${n.logical}: no variant '${n.id}'`);
  }
  for (const al of aliases) {
    let hit = 0;
    for (const [k, list] of entries) {
      if (k === 'characters' || k.split('.')[1] !== al.logical) continue;
      const own = list.find((x) => x.id === al.id);
      if (!own) continue;
      hit++;
      for (const word of al.forms) if (!list.some((x) => x.id === al.id && x.word === word)) list.push({ word, id: al.id, display: own.display });
    }
    if (!hit) throw new Error(`alias.${al.logical}: ${al.alias} -> ${al.id}: no such variant`);
  }
  const characterEntries = model.map((c) => ({ word: c.noun, id: c.id, display: c.noun }));
  entries.set('characters', characterEntries);
  for (const s of synonyms) {
    const target = lemmaOfPhrase(s.target);
    let hit = 0;
    for (const [k, list] of entries) {
      const logical = k === 'characters' ? 'characters' : k.split('.')[1];
      if (logical !== s.logical) continue;
      for (const e of list.filter((x) => x.word === target)) { list.push({ word: s.alias, id: e.id, display: e.display }); hit++; }
    }
    if (!hit) throw new Error(`synonym ${s.logical}: ${s.alias} -> ${s.target}: no such word (words are the generated lemmas, e.g. 'medical_mask')`);
  }
  // AV: a word of a new character that ends in a part word ("short_hair") must not hide the old reading "short" + hair of the
  // original characters: when its first part is already an option word of one of them, the new character uses that word instead.
  const CORE_IDS = new Set(['robot', 'person', 'emoji']);
  const PART_WORD = new Set(['hair', 'hairstyle', 'haircut', 'mouth', 'eye', 'eyes', 'nose', 'beard', 'eyebrow', 'brow', 'head', 'face', 'mask', 'cheek', 'accessory']);
  const coreWords = new Set();
  for (const [k, list] of entries) if (k !== 'characters' && CORE_IDS.has(k.split('.')[0])) for (const e of list) coreWords.add(e.word);
  for (const [k, list] of entries) {
    if (k === 'characters' || CORE_IDS.has(k.split('.')[0])) continue;
    for (const e of list) {
      const parts = e.word.split('_');
      if (parts.length > 1 && PART_WORD.has(parts.at(-1)) && coreWords.has(parts.slice(0, -1).join('_'))) e.word = parts.slice(0, -1).join('_');
    }
  }
  const options = new Set();
  for (const [k, list] of entries) if (k !== 'characters') for (const e of list) if (e.word !== OPTIONAL_NONE && e.word !== 'style') options.add(e.word);

  // ---- legend.sop ----
  const L = [];
  L.push(wire('gen.ui.avatar', 'core.note', [['text', note]]));
  L.push(wire('legend.ui.avatar', 'core.legend', [['namespace', 'ui.avatar'], ['version', '0.2.0'], ['imports', 'core'], ['imports', 'kids.common'],
    ['doc', `The avatar: a character drawn by DiceBear (${model.map((c) => `${c.noun} = ${c.style}`).join(', ')}). The types, keys and variants below are the style definitions of the library.`]]));
  L.push(wire('ui.avatar.character', 'core.type', [['extends', 'core.state'], ['doc', 'Which character is shown, its name and the seed that drew it. The world state holds character, name, seed and one object per character style.'],
    ['example', 'Become a person.']]));
  L.push(wire('ui.avatar.character.active', 'core.key', [['value', 'atom'], ['card', 'one'], ['ask', `Which character are you (${model.map((c) => c.noun).join(', ')})?`], ['doc', `One of: ${model.map((c) => c.noun).join(', ')}.`]]));
  L.push(wire('ui.avatar.character.name', 'core.key', [['value', 'string'], ['card', 'one'], ['ask', 'What is your name?']]));
  L.push(wire('ui.avatar.character.seed', 'core.key', [['value', 'string'], ['card', 'one'], ['ask', 'Which seed drew you?']]));
  for (const c of model) {
    L.push(wire(`ui.avatar.${c.id}`, 'core.type', [['extends', 'core.state'],
      ['doc', `The ${c.noun} (DiceBear style ${c.style}, ${c.license}, by ${c.creator}). Components: ${c.components.map((x) => x.key).join(', ')}. Colors: ${c.colors.map((x) => x.key).join(', ')}.`],
      ['example', `Make your ${c.components[0].key === 'head' ? 'hair an afro' : 'eyes round'}.`]]));
    for (const comp of c.components) {
      const opts = comp.variants.map((v) => v.id);
      L.push(wire(`ui.avatar.${c.id}.${comp.key}`, 'core.key', [['value', 'atom'], ['card', 'one'], ['ask', ASK[comp.key] ?? `Which ${LABEL[comp.key] ?? comp.key} do you have?`],
        ['doc', `One of: ${(comp.optional ? [OPTIONAL_NONE, ...opts] : opts).join(', ')}.`]]));
    }
    for (const col of c.colors) {
      L.push(wire(`ui.avatar.${c.id}.${col.key}Color`, 'core.key', [['value', 'atom'], ['card', 'one'], ['ask', `Which color is your ${COLOR_LABEL[col.key] ?? col.key}?`],
        ['doc', `A 6-digit hex entry of the style palette: ${col.values.join(', ')}${col.notEqualTo.length ? `; never equal to the ${col.notEqualTo.join(', ')} color` : ''}.`]]));
    }
  }

  // ---- lexicon.sop ----
  const X = [];
  X.push(wire('gen.ui.avatar.lexicon', 'core.note', [['text', note]]));
  X.push(lexicon('lex.ui.avatar.options', 'noun', 'Every variant of every component as the words people say (generated, singular), plus synonyms from lexicon.extra.sop', [...options]));
  X.push(lexicon('lex.ui.avatar.characters', 'noun', 'The characters (generated) and their synonyms', [...new Set(entries.get('characters').map((e) => e.word))]));
  X.push(lexicon('lex.ui.avatar.colors', 'noun', 'Color names; light_ and dark_ variants of the main hues; inherits the shared colour names of lang.common', Object.keys(names), [['extends', '$lex.lang.colour']]));
  X.push(lexicon('lex.ui.avatar.data.colornames', 'data', 'ops data: <color name>:<hex>', Object.entries(names).map(([n, h]) => `${n}:${h}`)));
  X.push(lexicon('lex.ui.avatar.data.characters', 'data', 'ops data: <word>:<character>:<display>', entries.get('characters').map((e) => `${e.word}:${e.id}:${e.display}`)));
  for (const c of model) {
    X.push(lexicon(`lex.ui.avatar.data.${c.id}.components`, 'data', `ops data: the components of the ${c.noun}, in style order`, c.components.map((x) => x.key)));
    X.push(lexicon(`lex.ui.avatar.data.${c.id}.optional`, 'data', `ops data: components of the ${c.noun} that can be absent (variant none)`, c.components.filter((x) => x.optional).map((x) => x.key)));
    X.push(lexicon(`lex.ui.avatar.data.${c.id}.colors`, 'data', `ops data: the colors of the ${c.noun}`, c.colors.map((x) => x.key)));
    for (const comp of c.components) {
      X.push(lexicon(`lex.ui.avatar.data.${c.id}.${comp.key}`, 'data', `ops data: <word>:<variant>:<display> of ${c.noun}.${comp.key}, in style order`, entries.get(`${c.id}.${comp.key}`).map((e) => `${e.word}:${e.id}:${e.display}`)));
    }
    for (const col of c.colors) X.push(lexicon(`lex.ui.avatar.palette.${c.id}.${col.key}`, 'data', `ops data: palette of ${c.noun}.${col.key}`, col.values));
  }
  const sep = '\n';
  const legendExtra = await readFile(path.join(WORLD, 'legend.extra.sop'), 'utf8').catch(() => '');   // the hand-written types of the knowledge base (kb.sop)
  return {
    'legend.sop': L.join(sep) + (legendExtra.trim() ? `${sep}${sep}${legendExtra.trim()}\n` : ''),
    'lexicon.sop': X.join(sep) + (verbatim.trim() ? `${sep}${verbatim}` : ''),
    summary: { core: ver.core, styles: ver.styles, options: options.size, characters: model.map((c) => c.id), synonyms: synonyms.length },
  };
}

