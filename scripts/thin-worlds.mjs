/**
 * THIN LIVE WORLDS table (worker-tasks 2026-11-14 06:20, item 1): per tab world, ONE generated row:
 *   own wires and lines by kind (schema, hooks, own, extras of patterns / lexicon / templates / operations, other code = renderer and engine),
 *   what it imports (std.* library modules, w.* published world schemas, k.* knowledge worlds), the reuse number (library report),
 *   and for every own part one of: truly own / general -> library / general -> w.* schema / knowledge -> k.*
 * The counts are read from the files; the verdict of each part is hand-written data (`scripts/thin-worlds.classes.json`, one entry per hand-written file or family of files),
 * and a part with no verdict is shown as `unclassified`, so a new file cannot slip in unjudged.
 *
 *   node scripts/thin-worlds.mjs [--json]      (markdown on stdout)
 * `thinTable(worlds)` is used by scripts/landing-table.mjs (markdown and html of the landing table).
 */
import { readFileSync, readdirSync, existsSync, statSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const KNOWLEDGE = new Set(['k.actions', 'k.animals', 'k.attributes', 'k.body', 'k.colours', 'k.commonsense', 'k.drawing', 'k.faces', 'k.feelings', 'k.food', 'k.geo', 'k.kinds', 'k.layouts', 'k.motion', 'k.objects', 'k.parts', 'k.people', 'k.scenes', 'k.shapes', 'k.space', 'k.time', 'k.units', 'k.values', 'k.wearables', 'k.words']);
const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
const isCode = (l) => l.trim() && !/^\s*(#|\/\/|\*|\/\*)/.test(l);
const lines = (text) => text.split('\n').filter(isCode).length;
const wires = (text) => text.split('\n').filter((l) => /^@/.test(l)).length;
const isGenerated = (f, text) => /generated/i.test(f) || /GENERATED|Generated (from|by)|generated by scripts/.test(text.split('\n').slice(0, 4).join('\n'));

/** The kind of a hand-written file: schema | hooks | own | extra | other (renderer, engine, data) | language (patterns, lexicon ... written by hand) | null (skipped). */
export function kindOf(f) {
  if (f === 'schema.sop') return 'schema';
  if (f === 'hooks.mjs') return 'hooks';
  if (f === 'own.mjs') return 'own';
  if (/\.extra\.sop$/.test(f)) return 'extra';
  if (f === 'world.sop' || f === 'legend.sop' || f === 'tests.sop' || f === 'tests.template.sop' || f === 'ops.mjs') return null;   // manifest, legend, tests; ops.mjs is the generated executor binding
  if (/\.mjs$/.test(f)) return 'other';
  if (/^(patterns|lexicon|templates|operations|matrix|describe|phrases|kb)/.test(f)) return 'language';
  return 'other';
}

/** { files: [{ file, kind, lines, wires }], totals by kind, imports } for the hand-written files of a world. */
export function inspect(id) {
  const dir = join(REPO, 'worlds', id);
  const files = [];
  const walk = (d, pre = '') => {
    for (const f of readdirSync(d).sort()) {
      const p = join(d, f);
      if (statSync(p).isDirectory()) { if (f !== 'vendor' && f !== 'node_modules') walk(p, `${pre}${f}/`); continue; }
      if (!/\.(sop|mjs)$/.test(f)) continue;
      const text = readFileSync(p, 'utf8');
      if (isGenerated(f, text)) continue;
      const kind = kindOf(f);
      if (!kind) continue;
      files.push({ file: pre + f, kind, lines: lines(text), wires: wires(text), text });
    }
  };
  walk(dir);
  const by = (k) => files.filter((x) => x.kind === k);
  const sum = (k, key) => by(k).reduce((a, x) => a + x[key], 0);
  const code = files.map((f) => f.text).join('\n');
  const uniq = (re, strip = (x) => x) => [...new Set([...code.matchAll(re)].map((m) => strip(m[0])))].sort();
  const manifest = existsSync(join(dir, 'world.sop')) ? readFileSync(join(dir, 'world.sop'), 'utf8') : '';
  const LIB = { acts: 'std.acts', space: 'std.space', 'session.things': 'std.things', 'session.dialogue': 'std.dialogue' };
  const viaWorld = [...manifest.matchAll(/imports=world\.([\w.]+)/g)].map((m) => LIB[m[1]]).filter(Boolean);
  const viaPath = (re, f) => [...code.matchAll(re)].map((m) => f(m[1]));
  const KMOD = { animals: 'k.animals', faces: 'k.faces', time: 'k.time', values: 'k.values', layouts: 'k.layouts', arrangement: 'k.layouts', commonsense: 'k.commonsense', catalog: 'k.objects' };
  const imports = {
    std: [...viaWorld, ...uniq(/\bstd\.[a-z]+(?:\.[a-z]+)?/g).filter((x) => !/^std\.(schema\.(thing|world|kind|slot))$/.test(x)).map((x) => x.split('.').slice(0, 2).join('.')).filter((x, i, a) => a.indexOf(x) === i)].filter((x, i, a) => a.indexOf(x) === i).sort(),
    w: [...new Set([...uniq(/(?<![\w./-])w\.(?:face|map|seating|timeline|list|lang\.(?:en|ro))\b(?!\()/g), ...viaPath(/src\/lang\/(en)\b/g, () => 'w.lang.en')])].sort(),
    k: [...new Set([...uniq(/(?<![\w./-])k\.[a-z]+\b/g).filter((x) => KNOWLEDGE.has(x)), ...viaPath(/src\/knowledge\/([a-z-]+)\.mjs/g, (m) => KMOD[m]).filter(Boolean)])].sort(),
  };
  return { id, files: files.map(({ text, ...r }) => r), schema: { lines: sum('schema', 'lines'), wires: sum('schema', 'wires') }, hooks: sum('hooks', 'lines'), own: sum('own', 'lines'),
    extras: { lines: sum('extra', 'lines'), wires: sum('extra', 'wires') }, other: sum('other', 'lines'), language: sum('language', 'lines'), imports };
}

const classesFile = join(REPO, 'scripts/thin-worlds.classes.json');
const classes = () => (existsSync(classesFile) ? JSON.parse(readFileSync(classesFile, 'utf8')) : {});
export const VERDICTS = ['truly own', 'general -> library', 'general -> w.* schema', 'knowledge -> k.*'];

/** The verdict of a file of a world: the entry whose `part` is the file name or a prefix ending in `*`. */
export function verdictOf(cls, id, file) {
  const list = cls[id]?.parts ?? [];
  return list.find((p) => p.part === file || (p.part.endsWith('*') && file.startsWith(p.part.slice(0, -1)))) ?? null;
}

/** One row per tab world: counts, imports, reuse, verdict per part. `worlds` is collectWorlds().worlds (group, reuse); `ids` limits the list. */
export function thinRows(worlds, ids) {
  const cls = classes();
  const BUILTIN_TABS = ['docs.editor', 'games.guess', 'games.hangman', 'games.tictactoe'];   // tabs the shell declares itself (worlds/ui.shell/ops.mjs)
  const tabs = ids ?? [...BUILTIN_TABS, ...readdirSync(join(REPO, 'worlds')).filter((d) => existsSync(join(REPO, 'worlds', d, 'world.sop')) && /^\s+tab=/m.test(readFileSync(join(REPO, 'worlds', d, 'world.sop'), 'utf8')))];
  if (!tabs.includes('ui.avatar') && existsSync(join(REPO, 'worlds/ui.avatar'))) tabs.push('ui.avatar');   // an icon with a popup, not a tab, but a live world with a face
  return tabs.sort().map((id) => {
    const r = inspect(id);
    const w = worlds.find((x) => x.id === id);
    const parts = r.files.filter((f) => f.kind !== 'language' || f.lines).map((f) => ({ ...f, v: verdictOf(cls, id, f.file) }));
    return { ...r, reuse: w?.reuse ?? null, parts, note: cls[id]?.note ?? '' };
  });
}

const cell = (s) => String(s).replace(/\|/g, '/');
const partText = (r) => {
  const by = {};
  for (const p of r.parts) {
    const k = p.v?.verdict ?? 'unclassified';
    (by[k] ??= []).push(`${p.file} ${p.lines}${p.v?.to ? ` -> ${p.v.to}` : ''}`);
  }
  return Object.entries(by).map(([k, l]) => `${k}: ${l.join(', ')}`).join('; ');
};

export function toMarkdown(rows) {
  const head = '| world | schema lines (wires) | hooks | own | extras lines (wires) | engine / renderer / data | imports std | imports w.* | imports k.* | reuse | own parts by verdict |\n| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |\n';
  return head + rows.map((r) => `| ${r.id} | ${r.schema.lines} (${r.schema.wires}) | ${r.hooks} | ${r.own} | ${r.extras.lines} (${r.extras.wires}) | ${r.other} | ${cell(r.imports.std.join(' ') || '-')} | ${cell(r.imports.w.join(' ') || '-')} | ${cell(r.imports.k.join(' ') || '-')} | ${r.reuse ?? '-'} | ${cell(partText(r))} |`).join('\n');
}

export function toHtml(rows) {
  return `<h2>Thin live worlds: what each tab world still owns</h2>
<p>Generated by <code>scripts/thin-worlds.mjs</code> from the files of each live world (hand-written lines only; generated files and tests are left out) and the verdict of each part in <code>scripts/thin-worlds.classes.json</code>.
Verdicts: <i>truly own</i> (renderer, engine), <i>general -&gt; library</i>, <i>general -&gt; w.* schema</i> (sop-knowledge-worlds), <i>knowledge -&gt; k.*</i>. A part with no verdict reads <i>unclassified</i>.</p>
<div class="scroll"><table><thead><tr><th>world</th><th class="num">schema lines (wires)</th><th class="num">hooks</th><th class="num">own</th><th class="num">extras lines (wires)</th><th class="num">engine, renderer, data</th><th>imports</th><th class="num">reuse</th><th>own parts by verdict</th></tr></thead><tbody>
${rows.map((r) => `<tr><td>${esc(r.id)}</td><td class="num">${r.schema.lines} (${r.schema.wires})</td><td class="num">${r.hooks}</td><td class="num">${r.own}</td><td class="num">${r.extras.lines} (${r.extras.wires})</td><td class="num">${r.other}</td><td style="white-space:normal">${esc(['std: ' + (r.imports.std.join(' ') || '-'), 'w: ' + (r.imports.w.join(' ') || '-'), 'k: ' + (r.imports.k.join(' ') || '-')].join('; '))}</td><td class="num">${r.reuse ?? '-'}</td><td style="white-space:normal;min-width:22rem">${esc(partText(r))}</td></tr>`).join('\n')}</tbody></table></div>
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const sm = await import('./build-system-map.mjs');
  const rows = thinRows(sm.collectWorlds().worlds);
  console.log(process.argv.includes('--json') ? JSON.stringify(rows, null, 1) : toMarkdown(rows));
}
