/**
 * Adds new cases to the case corpus (training/eval/cases.jsonl) and LISTS every case that changed from right to wrong since the last run (never hides them).
 * Format and rules: scripts/lib/cases-corpus.mjs (sopworld failure-ledger format, observations, append-only).
 *
 * Sources (all ingested; `--sources` picks a subset, default all but a grid re-run):
 *   ledger    training/eval/failures.jsonl: every row, as a WRONG case (imported once per id; later observations come from a replay).
 *   owner     the three owner logs replayed on this build (scripts/eval-owner-log.mjs): right / wrong / unchecked, with the cause group of a wrong row.
 *   transfer  scripts/exp-transfer.mjs T1 + T2 (+ T3), matrix reasoner: right / na / wrong per cell, with the pair of worlds (from>to).
 *   holes     training/eval/lang-holes.jsonl: the cases of the holes of English (relative clauses, "some of", "the other one", "or", negated acts, temporal prepositions; handover/lang.en), replayed on this build
 *             (scripts/lib/lang-holes.mjs), with a case id per hole case so a hole closing (wrong > right) or a case breaking (right > wrong) shows in the list
 *   grid      docs/webchat/coverage-grid.json (generated by scripts/coverage-grid.mjs; `--regrid` re-runs it first, about 3 minutes): one case per sentence and reasoner,
 *             wrong = a hole (no state change / no answer).
 *
 * failures.jsonl stays as it is: the FAILING VIEW that build-failure-ledger.mjs, analyze-failures.mjs and eval-ablation.mjs read and that other agents append to. The corpus
 * ingests it on every run (so a new ledger row becomes a case), and `--failing` prints the failing view of the corpus (cases whose last observation is wrong).
 *
 *   node scripts/update-cases.mjs [--sources ledger,owner,transfer,grid] [--regrid] [--dry] [--failing] [--strict]
 * `--strict` exits 3 when there is a right-to-wrong change (the list is printed either way). A run that adds or changes something appends a line to cases-runs.jsonl.
 */
import { readFileSync, existsSync, mkdtempSync, rmSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { causeOf, stageOf } from './lib/failure-cause.mjs';
import { REPO, CORPUS, RUNS, caseId, readCorpus, readRuns, latest, appendRows, appendRun } from './lib/cases-corpus.mjs';

const arg = (k, d) => { const i = process.argv.indexOf(`--${k}`); return i > 0 ? process.argv[i + 1] : d; };
const has = (k) => process.argv.includes(`--${k}`);
const sources = new Set((arg('sources', 'ledger,owner,transfer,grid,holes')).split(','));
const today = new Date().toISOString().slice(0, 10);
const build = spawnSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: REPO, encoding: 'utf8' }).stdout.trim();
const clip = (s, n = 300) => String(s ?? '').replace(/\s+/g, ' ').slice(0, n);

const CORPUS_F = arg('corpus', CORPUS), RUNS_F = arg('runs', RUNS);   // other files only for tests
const corpus = readCorpus(CORPUS_F);
const last = latest(corpus);
const run = (readRuns(RUNS_F).at(-1)?.run ?? 0) + 1;

if (has('failing')) {
  const failing = [...last.values()].filter((r) => r.outcome === 'wrong');
  const by = {};
  for (const r of failing) { const k = `${r.group ?? '?'} [${r.stage ?? '?'}]`; by[k] = (by[k] ?? 0) + 1; }
  console.log(`failing view: ${failing.length} of ${last.size} cases`);
  for (const [k, n] of Object.entries(by).sort((a, b) => b[1] - a[1])) console.log(`${String(n).padStart(6)}  ${k}`);
  process.exit(0);
}

/** candidates: [{kind, text, tab, language, happened, expected, class, source, outcome, ...extra}] */
const cand = [];
const add = (c) => cand.push({ language: 'en', tab: null, class: 'unclassified', ...c, happened: clip(c.happened), expected: typeof c.expected === 'string' ? c.expected : JSON.stringify(c.expected ?? null) });

if (sources.has('owner')) {
  const { replay } = await import('./eval-owner-log.mjs');
  for (const sfx of ['', 'b', 'c']) {
    const name = `owner-log-2026-11-13${sfx}`;
    const rep = await replay({ log: join(REPO, `training/eval/${name}.jsonl`), checks: sfx ? '/nonexistent' : undefined });
    for (const r of rep) {
      const happened = r.error ? `(error) ${r.error}` : !r.reply?.trim() ? '(no reply)' : `${r.reply}${r.worlds?.length ? ` [worlds: ${r.worlds.join(',')}]` : ''}${r.failing?.length ? ` [check: ${r.failing.join(' ')}]` : ''}`;
      const asked = r.class !== 'ok' && r.expected != null && r.expected !== '';
      // same convention as build-failure-ledger: a checked row is right or wrong; an unchecked "ok" row is only wrong when it is checked and fails; an unchecked asked row stays wrong
      const outcome = r.outcome === 'right' ? 'right' : r.outcome === 'wrong' ? 'wrong' : asked ? 'wrong' : 'unchecked';
      add({ kind: 'owner-log', text: r.text, tab: r.tab, language: r.lang, happened, expected: r.expected ?? (r.failing ?? []).join(' '), class: r.class, source: `${name}#${r.i}`, outcome, was_passing: r.class === 'ok' && outcome === 'wrong' });
    }
  }
}

if (sources.has('holes')) {
  const { runHoleCases } = await import('./lib/lang-holes.mjs');
  for (const r of await runHoleCases()) add({ kind: 'lang-hole', text: r.text, tab: r.tab, happened: r.happened, expected: r.expected, class: `lang-hole:${r.hole}`, source: `lang-holes#${r.id}`, outcome: r.outcome });
}

const VIEW_WORLD = { avatar: 'ui.avatar', seating: 'plan.seating', talk: 'talk', draw: 'art.draw', chart: 'data.charts', doc: 'docs.editor', time: 'plan.timeline', map: 'geo.map' };
const VIEW_TAB = { avatar: 'robot', seating: 'seating', talk: 'talk', draw: 'draw', chart: 'charts', doc: 'editor', time: 'talk', map: 'talk' };
if (sources.has('transfer')) {
  const dir = mkdtempSync(join(tmpdir(), 'cases-transfer-'));
  const rows = [];
  for (const [file, args] of [['t12.jsonl', []], ['t3.jsonl', ['--only', 't3']]]) {
    const r = spawnSync(process.execPath, [join(REPO, 'scripts/exp-transfer.mjs'), ...args, '--out', join(dir, file)], { cwd: REPO, encoding: 'utf8', maxBuffer: 1 << 28 });
    if (existsSync(join(dir, file))) rows.push(...readFileSync(join(dir, file), 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l)));
    else console.error(`exp-transfer ${args.join(' ')} gave no rows: ${clip(r.stderr, 200)}`);
  }
  rmSync(dir, { recursive: true, force: true });
  const out = (v) => (v.startsWith('wrong') ? 'wrong' : v);   // right | na | wrong
  for (const r of rows) {
    if (r.exp === 'T1') add({ kind: 'transfer', exp: 'T1', text: r.text, tab: VIEW_TAB[r.from], happened: `${r.reply} [${r.verdict}]`, expected: `${r.expect === 'ok' ? 'the thing arrives with its words kept' : 'a plain refusal: not applicable'} (${r.thing})`, class: `transfer:T1:${r.from}>${r.to}`, source: `T1 thing transfer (matrix) ${r.thing} > ${r.to}`, outcome: out(r.verdict), pair: `${VIEW_WORLD[r.from]}>${VIEW_WORLD[r.to]}` });
    else if (r.exp === 'T2') add({ kind: 'transfer', exp: 'T2', text: r.ask, tab: { talk: 'talk', seating: 'seating', avatar: 'avatar' }[r.view], happened: `${r.reply} [${r.verdict}]`, expected: `the taught fact "${r.fact}" (taught in ${r.taughtIn}) is used or refused plainly in ${r.view}`, class: `transfer:T2:${r.taughtIn}>${r.view}`, source: 'T2 taught-fact transfer (matrix) scripts/exp-transfer.mjs', outcome: out(r.verdict), cause: r.cause, ...(r.other ? { pair: `${VIEW_WORLD[r.taughtIn]}>${VIEW_WORLD[r.view]}` } : {}) });
    else if (r.exp === 'T3') add({ kind: 'transfer', exp: 'T3', text: r.ask ?? `(no probe) ${r.fact}`, tab: { drawing: 'draw', diagram: 'diagram', talk: 'talk' }[r.view], happened: `${r.reply} [${r.verdict}]`, expected: `the fact "${r.fact}" (${r.taught ? 'taught in a sentence' : 'in the catalog'}) shows in the answer: ${[].concat(r.expect ?? 'na').join(' / ')}`, class: `transfer:T3:knowledge>${r.view}`, source: 'T3 rule transfer (matrix) scripts/exp-transfer.mjs', outcome: out(r.verdict), cause: r.cause, pair: `knowledge>${{ drawing: 'art.draw', diagram: 'diagram.sketch', talk: 'talk' }[r.view]}` });
  }
}

if (sources.has('grid')) {
  if (has('regrid')) {
    const r = spawnSync(process.execPath, [join(REPO, 'scripts/coverage-grid.mjs'), '--json', 'docs/webchat/coverage-grid.json'], { cwd: REPO, encoding: 'utf8', maxBuffer: 1 << 28 });
    if (r.status !== 0) console.error(`coverage-grid failed: ${clip(r.stderr, 300)}`);
  }
  const f = join(REPO, 'docs/webchat/coverage-grid.json');
  if (existsSync(f)) {
    const g = JSON.parse(readFileSync(f, 'utf8'));
    const CHANGING = ['make', 'remove', 'change', 'place', 'connect', 'group', 'copy', 'load'];
    if (g.version === 2) {
      // grid v2 (2026-11-14): sentences the generator can stand behind; a hole counts only when the setup was confirmed (else `unchecked`); a reply of another tab world is a cross-world capture
      for (const w of g.worlds) for (const c of w.cells) for (const rs of ['ops', 'matrix']) if (c[rs]) {
        const capture = c[`${rs}Capture`];
        const miss = c[rs] === 'miss', confirmed = c[`${rs}Setup`] !== false;
        add({ kind: 'grid', text: c.text, tab: w.tab ?? w.id, happened: `${c[`${rs}Reply`] ?? ''} [${c[rs]}${capture ? `; answered by ${capture}` : ''}${confirmed ? '' : '; setup unconfirmed'}]`,
          expected: capture ? `the world of the open tab (${w.id}) answers or asks; ${capture} does not take the sentence` : c.act === 'ask' ? 'an answer that is not a refusal' : c.judge === 'reply' ? 'a reply that is not a refusal (a question back is fine)' : CHANGING.includes(c.act) ? 'the state of the world changes' : 'a reply that is not a refusal',
          class: capture ? 'foreign-world:grid-capture' : `grid:${c.act}`, source: `coverage-grid-v2 ${w.id} (${rs})`, outcome: capture ? 'wrong' : miss ? (confirmed ? 'wrong' : 'unchecked') : 'right', world: w.id, reasoner: rs, act: c.act, verb: c.verb ?? null, grid_kind: c.kind, form: c.form });
      }
      // grid v1 had generator defects (placeholders, internal kind names, impossible combinations, an empty state): its rows are retired, not deleted
      for (const r of last.values()) if (r.kind === 'grid' && /^coverage-grid (?!v2)/.test(r.source ?? '') && r.outcome !== 'retired') add({ kind: 'grid', text: r.text, tab: r.tab, happened: r.happened, expected: r.expected, class: r.class, source: r.source, outcome: 'retired', world: r.world, reasoner: r.reasoner, act: r.act, retired: 'grid v1: the generator, not the system, produced this sentence or its state (2026-11-14)' });
    } else {
      for (const w of g.worlds) for (const c of w.cells) for (const rs of ['ops', 'matrix']) if (c[rs]) {
        add({ kind: 'grid', text: c.text, tab: w.id, happened: `${c[`${rs}Reply`] ?? ''} [${c[rs]}]`, expected: c.act === 'ask' ? 'an answer that is not a refusal' : CHANGING.includes(c.act) ? 'the state of the world changes' : 'a reply that is not a refusal', class: `grid:${c.act}`, source: `coverage-grid ${w.id} (${rs})`, outcome: c[rs] === 'miss' ? 'wrong' : 'right', world: w.id, reasoner: rs, act: c.act, verb: c.verb ?? null, grid_kind: c.kind });
      }
    }
  }
}

const replayedCount = cand.length;
if (sources.has('ledger')) {
  for (const l of readFileSync(join(REPO, 'training/eval/failures.jsonl'), 'utf8').split('\n').filter(Boolean)) {
    const r = JSON.parse(l);
    const id = caseId(r.source, r.text, r.tab);
    if (last.has(id)) continue;   // the ledger is imported once; a replay observes the case after it (its history is kept: wrong, then right)
    add({ kind: 'ledger', text: r.text, tab: r.tab, language: r.language ?? 'en', happened: r.happened, expected: r.expected, class: r.class ?? 'unclassified', source: r.source, outcome: 'wrong', cause: r.cause, was_passing: r.was_passing, first_seen_ledger: r.first_seen, build_ledger: r.build });
  }
}


const ordered = [...cand.slice(replayedCount), ...cand.slice(0, replayedCount)];   // ledger imports first, then what the replays say now
// ---- merge: append new ids and changed outcomes -------------------------------------------------------------------------------------------------
const cur = new Map(last);
const fresh = [], regress = [], fixed = [];
let added = 0;
for (const c of ordered) {
  const id = caseId(c.source, c.text, c.tab);
  const prev = cur.get(id);
  if (prev && prev.outcome === c.outcome) continue;
  const row = { id, ...c, first_seen: today, build, run };
  if (c.first_seen_ledger) { row.first_seen = c.first_seen_ledger; row.build = c.build_ledger ?? build; }
  delete row.first_seen_ledger; delete row.build_ledger;
  if (row.cause === undefined || row.cause === null) delete row.cause;
  if (row.was_passing === undefined) delete row.was_passing;
  if (c.outcome === 'wrong') { row.group = causeOf({ text: c.text, tab: c.tab, language: c.language, happened: c.happened, class: c.class, source: c.source }); row.stage = stageOf(row.group); }
  if (prev) { row.changed = `${prev.outcome}>${c.outcome}`; row.previous_build = prev.build; (prev.outcome === 'right' && c.outcome === 'wrong' ? regress : prev.outcome === 'wrong' && c.outcome === 'right' ? fixed : []).push(row); }
  else added++;
  fresh.push(row); cur.set(id, row);
}
const byKind = {}; for (const r of fresh) { const k = `${r.kind}/${r.outcome}${r.changed ? ' (changed)' : ''}`; byKind[k] = (byKind[k] ?? 0) + 1; }
console.log(`case corpus run ${run}: ${cand.length} observations read, ${added} new cases, ${fresh.length - added} changed outcomes; corpus had ${last.size} cases`);
console.log(Object.entries(byKind).sort().map(([k, n]) => `  ${String(n).padStart(5)}  ${k}`).join('\n'));
console.log(`\nRIGHT -> WRONG since the last observation: ${regress.length}${regress.length ? ' (listed in full, not hidden)' : ''}`);
for (const r of regress) console.log(`  [${r.kind}] ${r.source} | ${clip(r.text, 90)} | now: ${clip(r.happened, 140)} | group: ${r.group} [${r.stage}] | was right at ${r.previous_build}`);
console.log(`WRONG -> RIGHT: ${fixed.length}${fixed.length ? ` (e.g. ${fixed.slice(0, 3).map((r) => clip(r.text, 50)).join(' / ')})` : ''}`);
if (!has('dry') && (fresh.length || has('always'))) {
  appendRows(fresh, CORPUS_F);
  appendRun({ run, date: today, build, added, changed: fresh.length - added, regressions: regress.map((r) => r.id), fixed: fixed.map((r) => r.id) }, RUNS_F);
  console.log(`appended ${fresh.length} observations to training/eval/cases.jsonl`);
}
if (has('strict') && regress.length) process.exit(3);
