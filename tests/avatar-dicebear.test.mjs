// ui.avatar on DiceBear: generated legend and lexicon, ops data consistency, vendored files, host option mapping.
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createEngine, runWorldTests } from '../src/dialog/index.mjs';
import { createFsLoader, DEFAULT_ROOT } from '../src/loaders/fs-loader.mjs';
import { generate, splitName, lemmaOf } from '../scripts/legend-from-dicebear.mjs';
import * as ops from '../worlds/ui.avatar/ops.mjs';
import { avatarOptions, normalizeState, partsCaption } from '../docs/webchat/ui/avatar.mjs';

const root = (p) => fileURLToPath(new URL(`../${p}`, import.meta.url));
const engine = await createEngine({ loader: createFsLoader({ roots: [DEFAULT_ROOT] }) });
const world = engine.set.get('ui.avatar');
const lex = (id) => world.lexicons.find((l) => l.id === id)?.words ?? [];
const CHARS = ['robot', 'person', 'emoji'];
const variantIds = (ch, key) => [...new Set(lex(`lex.ui.avatar.data.${ch}.${key}`).map((w) => w.split(':')[1]))];

test('legend.sop and lexicon.sop are exactly what the generator produces from the vendored style definitions', async () => {
  const out = await generate();
  for (const f of ['legend.sop', 'lexicon.sop']) assert.equal(await readFile(root(`worlds/ui.avatar/${f}`), 'utf8'), out[f], `${f} is stale: run node scripts/legend-from-dicebear.mjs`);
  assert.match(out['legend.sop'], /^@gen\.ui\.avatar core\.note\n {4}text="Generated by scripts\/legend-from-dicebear\.mjs from DiceBear 10\.7\.0 \(styles 10\.6\.0\); do not edit by hand"/);
});

test('generator word splitting', () => {
  assert.deepEqual(splitName('angryWithFang'), ['angry', 'with', 'fang']);
  assert.deepEqual(splitName('bigSmile'), ['big', 'smile']);
  assert.deepEqual(splitName('smileLOL'), ['smile', 'lol']);
  assert.deepEqual(splitName('glasses2'), ['glasses', '2']);
  assert.equal(lemmaOf(splitName('glasses2')), 'glass');
  assert.equal(lemmaOf(splitName('medicalMask')), 'medical_mask');
});

test('legend: one type per character, one key per component and per color', () => {
  const L = engine.set.legends;
  for (const t of ['ui.avatar.character', 'ui.avatar.robot', 'ui.avatar.person', 'ui.avatar.emoji']) assert.ok(L.hasType(t), t);
  for (const k of ['ui.avatar.robot.eyes', 'ui.avatar.robot.top', 'ui.avatar.robot.bodyColor', 'ui.avatar.person.expression', 'ui.avatar.person.headContrastColor', 'ui.avatar.emoji.faceColor', 'ui.avatar.emoji.face', 'ui.avatar.character.seed']) {
    assert.ok(L.keyInfo(k), k);
  }
  assert.match(L.keyInfo('ui.avatar.robot.eyes').ask, /Which eyes do you have\?/);
  assert.deepEqual(engine.problems().filter((p) => /ui\.avatar/.test(p)), []);
});

test('world: at least 60 tests, all pass; ops.mjs imports nothing', async () => {
  assert.ok(world.tests.length >= 60, `${world.tests.length} tests`);
  const r = await runWorldTests(engine, 'ui.avatar');
  assert.deepEqual(r.failed, []);
  const src = await readFile(root('worlds/ui.avatar/ops.mjs'), 'utf8');
  assert.doesNotMatch(src, /^\s*import[\s{(*]/m);
  assert.doesNotMatch(src, /\bimport\s*\(/);
  assert.doesNotMatch(src, /\bfrom ['"]/);
});

test('every lexicon entry the formalizer can match has at most three words and a singular last word', () => {
  for (const id of ['lex.ui.avatar.options', 'lex.ui.avatar.characters', 'lex.ui.avatar.colors']) {
    for (const w of lex(id)) assert.ok(w.split('_').length <= 3, `${id}: ${w}`);
  }
});

test('initial state and mood table only use variants and palette entries of the style definitions', () => {
  const s = ops.initialState();
  assert.equal(s.character, 'robot');
  for (const ch of CHARS) {
    for (const key of lex(`lex.ui.avatar.data.${ch}.components`)) assert.ok([...variantIds(ch, key), 'none'].includes(s[ch][key]), `${ch}.${key}=${s[ch][key]}`);
    for (const key of lex(`lex.ui.avatar.data.${ch}.colors`)) assert.ok(lex(`lex.ui.avatar.palette.${ch}.${key}`).includes(s[ch].colors[key]), `${ch}.colors.${key}`);
  }
  for (const [mood, spec] of Object.entries(ops.MOODS)) {
    assert.ok(variantIds('person', 'expression').includes(spec.person), `${mood} person ${spec.person}`);
    for (const ch of ['robot', 'emoji']) for (const k of ['eyes', 'mouth']) assert.ok(variantIds(ch, k).includes(spec[ch][k]), `${mood} ${ch}.${k}=${spec[ch][k]}`);
  }
});

test('every synonym and every spoken part resolves to something real', () => {
  const comps = new Set(CHARS.flatMap((ch) => lex(`lex.ui.avatar.data.${ch}.components`)));
  for (const [word, keys] of Object.entries(ops.PART_KEYS)) for (const k of keys) assert.ok(comps.has(k), `${word} -> ${k}`);
  assert.ok(lex('lex.ui.avatar.options').includes('dish') && lex('lex.ui.avatar.options').includes('goggle'));
});

test('surprise me and change everything always leave a valid state, and a seed reproduces the look', async () => {
  const s = engine.createSession();
  for (const cmd of ['Surprise me.', 'Change everything.', 'Become a person.', 'Surprise me.', 'Change everything.', 'Turn into an emoji.', 'Surprise me.', 'Change everything.']) await s.send(cmd);
  const st = s.state('ui.avatar');
  for (const ch of CHARS) {
    for (const key of lex(`lex.ui.avatar.data.${ch}.components`)) assert.ok([...variantIds(ch, key), 'none'].includes(st[ch][key]), `${ch}.${key}=${st[ch][key]}`);
    for (const key of lex(`lex.ui.avatar.data.${ch}.colors`)) assert.ok(lex(`lex.ui.avatar.palette.${ch}.${key}`).includes(st[ch].colors[key]));
  }
  assert.notEqual(st.seed, 'psys2');
  const a = engine.createSession(), b = engine.createSession();
  await a.send('Use the seed banana.'); await b.send('Use the seed banana.');
  assert.deepEqual(a.state('ui.avatar').robot, b.state('ui.avatar').robot);
  await a.send('Use the seed apple.');
  assert.notDeepEqual(a.state('ui.avatar').robot, b.state('ui.avatar').robot);
});

test('a glow is never the same color as the body', async () => {
  const s = engine.createSession();
  for (let i = 0; i < 12; i++) { await s.send(`Use the seed s${i}.`); const c = s.state('ui.avatar').robot.colors; assert.notEqual(c.glow, c.body); }
  await s.send('Make your body mint.'); await s.send('Make your glow mint.');
  const c = s.state('ui.avatar').robot.colors; assert.notEqual(c.glow, c.body);
});

test('only another character can do it: the avatar turns into that character and says so', async () => {
  const s = engine.createSession();
  const r = await s.send('Wear a medical mask.');
  assert.equal(s.state('ui.avatar').character, 'person');
  assert.match(r.text, /turned into a person/);
  const q = engine.createSession();
  assert.match((await q.send('Make the background pink.')).text, /pink|closest|background/);
  await q.send('Become a person.');
  const amb = await q.send('Make the background pink.');
  assert.match(amb.text, /no background color/);
});

